/**
 * 頁に出す見本の一覧を選ぶ (#2016)。 部品の頁で一覧の欄に出す読み込みの状態も、ここで導く (#2018)。
 *
 * 選び方は 3 通り。 部品の頁は後から読み込む一覧を使い、それ以外の頁は束ねてある一覧から引き、
 * 縦列の名前が無い時は空にする。
 *
 * ## 同じ入力なら同じ配列を返す
 *
 * `CATALOG_ITEMS[slug] ?? []` は当たらなかった時に **毎回新しい空配列** を返す。 呼ぶたびに
 * 別の配列になると、この値を依存に持つ絞り込みと選んでいる項目が描き直しのたびにやり直される。
 * 見本は 506 枚あり、絞り込みは 1 枚ごとに題 / 副題 / id / 和名 / 英名 の 5 つを小文字にして
 * 照合するため、空振りでも数え直しの分だけ描画が遅れる。
 *
 * 頁の中に書かずに切り出したのは、**同じ入力で同じ配列が返る** ことを直接測れるようにするため。
 * 頁ごと描いて測ると、絞り込みがやり直されたかを外から観測できない。
 */
import { useMemo } from "react";

import { CATALOG_ITEMS, type CatalogItem } from "../lib/catalog-items";

/** 部品の頁の縦列の名前。 この頁だけ一覧を後から読み込む (CAR-1613) */
export const 部品の頁 = "parts";

/**
 * 頁に出す見本の一覧。
 *
 * @param 縦列 - 頁の縦列の名前 (`useParams` が返す値。 URL に無ければ `undefined`)
 * @param 後から読んだ部品 - 部品の頁で後から読み込んだ一覧。 他の頁では見ない
 */
export function useCategoryItems(
  縦列: string | undefined,
  後から読んだ部品: CatalogItem[],
): CatalogItem[] {
  return useMemo(
    () => (縦列 === 部品の頁 ? 後から読んだ部品 : 縦列 ? (CATALOG_ITEMS[縦列] ?? []) : []),
    [縦列, 後から読んだ部品],
  );
}

/** 部品の一覧を後から読み込んだ結果。 まだ終わっていなければ `null` */
export type 部品の読込結果 = "loaded" | "error" | null;

/** 一覧の欄に出す読み込みの状態 */
export type 部品の読込の見せ方 = "idle" | "loading" | "loaded" | "error";

/**
 * 一覧の欄に出す読み込みの状態を、縦列と読み込みの結果から導く (#2018)。
 *
 * 部品の頁で結果がまだ無ければ読み込み中、他の頁では何もしていない。
 *
 * ## 状態として持たない理由
 *
 * `/catalog/:slug` は縦列が変わっても頁の部品を作り直さない。 読み込み中かどうかを状態で持つと、
 * 別の縦列から部品の頁へ移った最初の描画では前の縦列の値 (`idle`) が残り、
 * 読み込みが始まる前に「該当する項目がありません」 が 1 回出る。
 * 縦列から導けば、移った最初の描画から読み込み中になる。
 *
 * @param 縦列 - 頁の縦列の名前
 * @param 結果 - 今回の読み込みの結果。 部品の頁を離れる時に `null` へ戻す
 */
export function 部品の読込を見せる(
  縦列: string | undefined,
  結果: 部品の読込結果,
): 部品の読込の見せ方 {
  if (縦列 !== 部品の頁) return "idle";
  return 結果 ?? "loading";
}
