/**
 * 見本帳で「見ている 1 件だけ」 に効く見せ方の持ち方 (#2022)。
 *
 * 速さ (#1355) / 描き方 (#1359) / 配色 (#1569) / 折れ線 (#1624) / 円 (#1645) / 傾き (#1659) /
 * パターン (#1696) の 7 つは、項目を選び直したら既定へ戻る。
 *
 * ## なぜ効果で戻さないか
 *
 * 効果が走るのは描き終えた後なので、選び直した最初の 1 コマは **前の項目の見せ方** で
 * 新しい図が描かれ、その後に描き直される。 描き方の既定は図ごとに違う (弧は継ぎ足すと起点を
 * 見失うので描き直しから始める、#1690) ため、既定を触っていない人にも出る。
 *
 * 代わりに **どの項目の見せ方かを値と一緒に持ち、描く時に読み替える**。 1 コマ目から新しい
 * 既定になり、戻し忘れも起きない。 同じ画面の拡大表示の倍率 (#1745) と並びの倍率 (#1749) が
 * 既に同じ形で、そちらのコメントが同じ理由を書いている。
 */
import { 既定の速さ, type 速さ } from "@/lib/playback-speed";
import { type 描き方 } from "@/lib/redraw-mode";
import { 既定の配色, type 配色 } from "@/lib/palette-switch";
import { 既定の折れ線の指定, type 折れ線の指定 } from "@/lib/chart-line-options";
import { 既定の円の見せ方, type 円の見せ方 } from "@/lib/chart-pie-options";
import { 既定の傾きの見せ方, type 傾きの見せ方 } from "@/lib/chart-slope-options";

export type 見せ方 = {
  速さ: 速さ;
  描き方: 描き方;
  配色: 配色;
  折れ線: 折れ線の指定;
  円: 円の見せ方;
  傾き: 傾きの見せ方;
  /** 選んでいるパターンの名前 (#1696)。 `null` は「まだ押していない」 = 元の見本 */
  パターン: string | null;
};

/** 見せ方と、その見せ方がどの項目のものか。 項目は `id`、`null` は「まだどれも見ていない」 */
export type 見せ方の持ち主 = { 項目: string | null; 値: 見せ方 };

/**
 * その項目を開いた時の見せ方。
 *
 * 図ごとに違うのは描き方だけで、残り 6 つは画面共通の既定をそのまま使う。
 * **既定は作り直さず参照をそのまま渡す** = 図を組み立てる `useMemo` がこの値を依存に持つため、
 * 毎回新しい object を作ると触っていない図まで描き直される。
 */
export function 開いた時の見せ方(この図の描き方: 描き方): 見せ方 {
  return {
    速さ: 既定の速さ,
    描き方: この図の描き方,
    配色: 既定の配色,
    折れ線: 既定の折れ線の指定,
    円: 既定の円の見せ方,
    傾き: 既定の傾きの見せ方,
    パターン: null,
  };
}

/**
 * 今描くべき見せ方。
 *
 * 持っている見せ方が今見ている項目のものなら、それをそのまま使う。 違う項目のもの
 * (選び直した直後 / まだ何も選んでいない) なら、この図を開いた時の見せ方を返す。
 */
export function 今の見せ方(
  状態: 見せ方の持ち主,
  見ている項目: string | null,
  この図の描き方: 描き方,
): 見せ方 {
  return 状態.項目 === 見ている項目 ? 状態.値 : 開いた時の見せ方(この図の描き方);
}
