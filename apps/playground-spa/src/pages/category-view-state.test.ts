/**
 * 見せ方の読み替え (#2022)。
 *
 * 項目を選び直した時に既定へ戻すのを、効果ではなく「描く時の読み替え」 で行う。
 * ここでは読み替えそのものを見る。 画面で 1 コマ目から効いていることは
 * `catalog-view-state.test.tsx` が見る。
 */
import { describe, it, expect } from "vitest";

import { 今の見せ方, 開いた時の見せ方, type 見せ方の持ち主 } from "./category-view-state";
import { 既定の速さ, 速さの選択肢 } from "@/lib/playback-speed";
import { 既定の描き方 } from "@/lib/redraw-mode";
import { 既定の配色, 配色の選択肢 } from "@/lib/palette-switch";
import { 既定の折れ線の指定, 折れ線の見せ方の選択肢 } from "@/lib/chart-line-options";
import { 既定の円の見せ方, 円の見せ方の選択肢 } from "@/lib/chart-pie-options";
import { 既定の傾きの見せ方, 傾きの見せ方の選択肢 } from "@/lib/chart-slope-options";

/**
 * 選択肢のうち既定でないもの。
 *
 * **値を書き写さない** = 選択肢が増減した時に、検査だけが古い値を使い続ける。
 * 既定しか無い項目は「既定へ戻った」 が読めないので、その場で落とす。
 */
function 既定と違う<T>(選択肢: readonly T[], 既定: T, 名: string): T {
  const 別 = 選択肢.find((v) => v !== 既定);
  if (別 === undefined) throw new Error(`${名} に既定以外の選択肢が無い (検査の前提が崩れた)`);
  return 別;
}

/** 何かを選んだ後の状態。 既定と全部違う値にして、既定へ戻ったことが読めるようにする */
function 選んだ後(項目: string | null): 見せ方の持ち主 {
  const 最初の折れ線 = 折れ線の見せ方の選択肢[0];
  if (最初の折れ線 === undefined)
    throw new Error("折れ線の見せ方が 1 つも無い (検査の前提が崩れた)");
  return {
    項目,
    値: {
      速さ: 既定と違う(速さの選択肢, 既定の速さ, "速さ"),
      描き方: "描き直す",
      配色: 既定と違う(配色の選択肢, 既定の配色, "配色"),
      折れ線: { ...既定の折れ線の指定, [最初の折れ線]: !既定の折れ線の指定[最初の折れ線] },
      円: 既定と違う(円の見せ方の選択肢, 既定の円の見せ方, "円の見せ方"),
      傾き: 既定と違う(傾きの見せ方の選択肢, 既定の傾きの見せ方, "傾きの見せ方"),
      パターン: "別の書き方",
    },
  };
}

describe("見せ方の読み替え (#2022)", () => {
  it("持ち主が今見ている項目と同じなら、選んだ値をそのまま返す", () => {
    const 状態 = 選んだ後("chart-line");
    expect(今の見せ方(状態, "chart-line", 既定の描き方)).toBe(状態.値);
  });

  it("持ち主が違う項目なら、その図を開いた時の見せ方を返す", () => {
    const 今 = 今の見せ方(選んだ後("chart-line"), "chart-pie", 既定の描き方);
    expect(今.速さ, "速さが前の項目のまま").toBe(既定の速さ);
    expect(今.描き方, "描き方が前の項目のまま").toBe(既定の描き方);
    expect(今.配色, "配色が前の項目のまま").toBe(既定の配色);
    expect(今.折れ線, "折れ線が前の項目のまま").toBe(既定の折れ線の指定);
    expect(今.円, "円が前の項目のまま").toBe(既定の円の見せ方);
    expect(今.傾き, "傾きが前の項目のまま").toBe(既定の傾きの見せ方);
    expect(今.パターン, "パターンが前の項目のまま").toBeNull();
  });

  it("描き方の既定だけは図ごとに違うので、渡した値がそのまま初期値になる", () => {
    // 弧は継ぎ足すと起点を見失うので描き直しから始める (#1690)
    expect(今の見せ方(選んだ後("chart-line"), "chart-radial", "描き直す").描き方).toBe("描き直す");
    expect(開いた時の見せ方("描き直す").描き方).toBe("描き直す");
  });

  it("まだ何も選んでいない状態で項目を見ていると、開いた時の見せ方を返す", () => {
    const 未選択: 見せ方の持ち主 = { 項目: null, 値: 開いた時の見せ方(既定の描き方) };
    expect(今の見せ方(未選択, "chart-line", "描き直す").描き方).toBe("描き直す");
  });

  it("既定は毎回作り直さず同じ参照を返す", () => {
    // 図を組み立てる `useMemo` がこの値を依存に持つ。 作り直すと、触っていない図まで
    // 毎回描き直される
    const 一回目 = 開いた時の見せ方(既定の描き方);
    const 二回目 = 開いた時の見せ方(既定の描き方);
    expect(一回目.折れ線, "折れ線の既定を作り直している").toBe(二回目.折れ線);
    expect(一回目.円, "円の既定を作り直している").toBe(二回目.円);
    expect(一回目.傾き, "傾きの既定を作り直している").toBe(二回目.傾き);
  });
});
