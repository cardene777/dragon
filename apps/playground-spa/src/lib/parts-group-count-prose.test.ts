import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, it, expect } from "vitest";

/**
 * 部品の節の説明に、手で数えた枚数を書き戻させない (#2208)。
 *
 * `parts.cdl.ts` は部品を群ごとの節に分けて書いており、各節の頭に「この群が何を見せるか」 の
 * 説明がある。 その説明が **「既存の N 枚」 / 「ここから N 枚」 という手で数えた枚数** を
 * 持っていた (5 つの節で 9 個)。 どれも検査が見ておらず、節を足すたびに人が数え直していた。
 *
 * ## 既にずれていた
 *
 * 数える母数が節によって違っていた。 「入口と出口を名前で選べる部品」 の節は部品の全件を数えて
 * 18 と書き、次の「前へ進むだけではない部品」 の節は繋ぎ方の部品だけを数えて 10 と書いていた。
 * どちらも「既存の N 枚」 と書いてあるので、読み手は 18 の次が 10 に減った理由を知れない。
 *
 * ## 何を止めるか
 *
 * 止めるのは **群の大きさを枚数で書く形** だけで、実測値を書いた注釈は止めない。
 * 「3 本ずつの 2 枚に割ると」 のような測った結果は、後から変わらないので人手の数ではない
 * (`rules/quality.md § 導出可能記述は人手で書かない` が対象にするのは実物から導ける値)。
 *
 * 判定は「枚」 の直前に数字があり、かつその数字が **群を指す言い回し** の中にある形に絞る。
 *
 * ## 走査した件数を出す
 *
 * 0 件は「該当なし」 と「測っていない」 の両方になりうる。 走査した注釈の行数を併記して、
 * 0 件が空振りでないことを読み手が分けられるようにする
 * (`rules/quality.md § 0 件を報告する時は母数を併記する`)。
 */

const ここ = dirname(fileURLToPath(import.meta.url));
const 対象のpath = join(ここ, "..", "topics", "catalog", "parts.cdl.ts");
const 本文 = readFileSync(対象のpath, "utf8");

/** `//` で始まる注釈の行 (行頭の空白は許す) */
const 注釈の行 = 本文.split("\n").filter((行) => /^\s*\/\//.test(行));

/**
 * 群の大きさを枚数で書いた形。
 *
 * 「既存の 18 枚」 / 「ここから 4 枚」 / 「残りの 6 枚」 のように、群を指す言い回しと枚数が
 * 並んだ形だけを拾う。 「2 枚に割ると」 のような実測の記述は拾わない。
 */
const 群の枚数 = /(既存|ここから|ここまで|残り|他)の\s*[0-9]+\s*枚/;

describe("部品の節の説明が手で数えた枚数を持たない (#2208)", () => {
  it("注釈を 1 行以上走査できている", () => {
    // 走査できていなければ、下の 0 件は「該当なし」 ではなく「測っていない」 になる
    expect(注釈の行.length, `${対象のpath} の注釈を 1 行も読めていない`).toBeGreaterThan(50);
  });

  it("群の大きさを枚数で書いた注釈が無い", () => {
    const 見つけた = 注釈の行.filter((行) => 群の枚数.test(行)).map((行) => 行.trim());
    expect(
      見つけた,
      `注釈 ${注釈の行.length} 行を走査した。 群の大きさは枚数ではなく群の名前で書く ` +
        `(節を足すたびに人が数え直す形になり、母数の違う数が並んで食い違う)`,
    ).toEqual([]);
  });

  it("植え込み対照 — 枚数を書き戻すと拾える", () => {
    // 判定が何も拾わない形になっていないことを、同じ判定に当てて確かめる
    const 植えた = ["// ここから 4 枚は 入った分をそのまま出さない繋ぎ方を表す。 既存の 22 枚は"];
    expect(植えた.filter((行) => 群の枚数.test(行))).toHaveLength(1);
  });

  it("植え込み対照 — 実測の記述は拾わない", () => {
    // 測った結果は後から変わらないので、人手の数として止めない
    const 植えた = [
      "// 3 本ずつの 2 枚に割ると 1 枚あたりの縦列が 3 本になり、どちらも指摘 0 件で収まる。",
      "// 負荷を出す側 = `fullPage` の写しを何枚も撮る検査 (20 枚)。",
    ];
    expect(植えた.filter((行) => 群の枚数.test(行))).toEqual([]);
  });
});
