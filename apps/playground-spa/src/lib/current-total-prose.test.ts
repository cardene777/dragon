import { readFileSync, readdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, it, expect } from "vitest";

/**
 * 注釈が「いまいくつあるか」 を数字で名乗らないことを見る (#2216)。
 *
 * 数える先が増えた日に書き換えを忘れると、注釈だけが古い数で残る。 実際に 4 箇所のうち
 * 1 箇所がずれていた (見本の総数を 506 と書いていたが、実物は一覧 363 と部品 108 の
 * 合計で 471)。 残る 3 箇所は当たっていたが、仕組みは同じで書き換えを忘れれば同じようにずれる。
 *
 * 数える先の名前を書けば、読み手はその場で数えられる
 * (`rules/quality.md § 導出可能記述は人手で書かない` の経路 2)。
 *
 * ## 総数を名乗る形だけを止める
 *
 * 「いくつ足したか」 の記録は今の数ではないので止めない。 判定は **名詞 + 助詞 + 数 +
 * 単位 + あり / ある** の並びに絞る = この形は「いま数えるとこうなる」 としか読めない。
 *
 * 実測でこの形は 4 件で、いずれも総数の宣言だった。 形を緩めて数と単位だけを見ると、
 * 過去に足した枚数の記録 (`catalog-motion-coverage.test.ts` に 7 行) を巻き込む。
 *
 * **拾う形と拾わない形の実例は、下の植え込み対照が文字列として持つ**。 注釈に書くと、この
 * file 自身が走査に引っかかる。
 *
 * ## 走査は対象ではなく除外で決める
 *
 * 走査する file を並べると、書き手が思い付いた場所が上限になる
 * (`rules/quality.md § 全件走査は除外を書く`)。 dir を降りて `.ts` / `.tsx` を全て読み、
 * 生成物の dir だけ外す。
 *
 * ## 説明書の側は別の検査が持つ
 *
 * `docs-derived-values.test.ts` が `docs/` と根の `*.md` に同じ決まりを課している。
 * そちらは量ごとに導き方を書く形で、こちらは注釈の言い回しで見る。
 */

const ここ = dirname(fileURLToPath(import.meta.url));
const 根 = join(ここ, "..", "..", "..", "..");

/** 降りない dir。 対象を並べる代わりに外す側を書く */
const 降りない = new Set([
  "node_modules",
  "dist",
  ".git",
  ".context",
  "coverage",
  "playwright-report",
]);

/** 走査する入口 */
const 入口 = [
  join(根, "apps", "playground-spa", "src"),
  join(根, "apps", "playground-spa", "tests"),
  join(根, "packages", "dragon", "src"),
  join(根, "packages", "dragon", "test"),
];

function fileを集める(dir: string): string[] {
  const 出た: string[] = [];
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (降りない.has(e.name)) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) 出た.push(...fileを集める(p));
    else if (/\.tsx?$/.test(e.name)) 出た.push(p);
  }
  return 出た;
}

/** 注釈の 1 行 (`//` の行と、ブロック注釈の `*` 始まりの行) */
const 注釈の行か = (行: string): boolean => /^\s*(\/\/|\*|\/\*)/.test(行);

const 注釈: Array<{ file: string; 行: string }> = 入口
  .flatMap((d) => fileを集める(d))
  .flatMap((p) =>
    readFileSync(p, "utf8")
      .split("\n")
      .filter(注釈の行か)
      .map((行) => ({ file: relative(根, p), 行: 行.trim() })),
  );

/**
 * 総数を名乗る形。
 *
 * 数える先の名前は決め打ちにしない = 名前を並べると、書き手が思い付いた名詞が上限になる。
 * 助詞と「あり / ある」 で挟まれた並びだけを見る。
 *
 * **「ある」 の後ろで文が切れることまで見る**。 切れずに名詞へ続く形 (「矢印が 2 本ある図」)
 * は、その数を持つものを指す言い回しであって総数の宣言ではない。 理由を続ける語
 * (「ため」 / 「ので」 / 「から」) は文が切れた後の接続なので拾う側に入れる。
 */
const 総数の形 = /[^\s。、]{1,12}[はが]\s*[0-9]+\s*[枚件種](あり|ある)(?=[、。」\s]|$|ため|ので|から)/;

const 拾う = (行: string): boolean => 総数の形.test(行);

describe("注釈が今の総数を数字で名乗らない (#2216)", () => {
  it("注釈を 1 行以上走査できている", () => {
    // 走査できていなければ、下の 0 件は「該当なし」 ではなく「測っていない」 になる
    expect(注釈.length, "走査した dir から注釈を 1 行も読めていない").toBeGreaterThan(1000);
  });

  it("総数を数字で名乗る注釈が無い", () => {
    const 見つけた = 注釈.filter(({ 行 }) => 拾う(行)).map((x) => `${x.file}: ${x.行}`);
    expect(
      見つけた,
      `注釈 ${注釈.length} 行を走査した。 今の総数は数字で書かず、数える先の名前を書く ` +
        `(数える先が増えた日に書き換えを忘れると、注釈だけが古い数で残る)`,
    ).toEqual([]);
  });

  it("植え込み対照 — 総数を書き戻すと拾える", () => {
    const 植えた = [
      " * 見本は 506 枚あり、絞り込みは 1 枚ごとに題 / 副題 / id / 和名 / 英名 の 5 つを",
      " * 表に無い軸は `直し方の既定` に落ちる。 軸は 67 件あり、直し方まで書けているのは",
      " * 上書きの表は 9 件しか持たず、分類は 11 件ある。 足した分類は上書きから漏れて",
      " * 繋ぎ方の部品は 26 枚あり、20 枚が繋いだ見本を持つ。 残る 6 枚がここに載る。",
      " * 見本の一覧は 80 件あるため開いた時に読む形で遅延させている。",
    ];
    expect(植えた.filter(拾う)).toHaveLength(5);
  });

  it("植え込み対照 — 足した数の記録や 1 件だけの話は拾わない", () => {
    const 植えた = [
      "// #1966 で体験の道筋に 5 つの気持ちの変種と、スタイルに値を並べる見本 11 枚 を足した",
      " * 名指しの書き方を確かめていたのは #2125 の見本 1 枚だけで、部品を足しても",
      " * 図に手動配置が 1 件あるだけで全部隠すと、触っていない箱で起きた本物の配置不良まで",
      " * (実測 = 走査 4181 件のうち 80 件が割れ、`API` は画面で通り枠で咎められていた)。",
      " * 同じ 2 者を結ぶ矢印が 2 本ある図は、記法の側で書き分けられない。",
    ];
    expect(植えた.filter(拾う)).toEqual([]);
  });
});
