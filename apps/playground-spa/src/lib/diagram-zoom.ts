/**
 * 図の倍率 (#1745 / #1749)。
 *
 * カタログは図を器に合わせて描くため、**器と図の大きさの差がそのまま読みやすさになる**。
 *
 * | どこ | 器 | 既定 |
 * |---|---|---|
 * | 拡大表示 | 1150 × 630px | 縦横とも収める |
 * | 並べて見る側 | 幅 874px (高さの上限なし) | 幅に合わせる |
 *
 * どちらの器にも箱の題が下限の 12px を割る図がある。 **枚数は書かない** = カタログに図を
 * 足すたびに動く (器ごとの実数は `packages/dragon/test/support/responsive-accepted.ts` の
 * `受け入れた一覧` が名前で持つ)。 どのくらい小さくなるかは同じ file の `代表的な図` が
 * 持ち、`readability-representative.test.ts` が描き直して突き合わせる。
 *
 * 逆に細い図は幅に合わせて引き伸ばされ、`parts-traffic-light-stack` は高さ 2292px になる。
 * 器を広げる余地は 6px しか無い (#1740 で実測)。
 *
 * 図を書き直す代わりに、**器に合わせる前提を外せる** ようにする。 はみ出す分は器が巻き取る。
 *
 * 画面から切り離してあるのは、倍率の決まり方を実際の描画に依らず確かめられるようにするため。
 * 器の寸法を受け取らないので、置き場所が増えてもこの file は変わらない。
 */

/** 倍率の刻み。 昇順で持つ (前後を index で辿るため)。 */
export const 倍率の刻み: readonly number[] = [0.5, 0.75, 1, 1.5, 2, 3];

/**
 * ホイールやつまみ操作で動かせる範囲 (#1961)。 **刻みの両端にそろえる** = ホイールで刻みの外まで
 * 行けると、ボタンの端の判定 (`端か`) と食い違い、押せるのに動かない状態が生まれる。
 */
export const 倍率の下限 = 倍率の刻み[0]!;
export const 倍率の上限 = 倍率の刻み[倍率の刻み.length - 1]!;

/** 器に合わせる指定。 数値の倍率と区別する。 */
export const 収める = "収める" as const;

/**
 * 倍率の指定。 `収める` か数値。
 *
 * 数値は刻みの値だけでなく、ホイールやつまみ操作で細かく動かした値も取る (#1961)。
 */
export type 倍率の指定 = typeof 収める | number;

/**
 * `収める` を画面に出す時の呼び名。
 *
 * **場所で変える**。 拡大表示は縦横とも器に収めるが、並べて見る側は幅にだけ合わせる =
 * 同じ言葉にすると、細い図が 1.7 倍に伸びるのを「収める」 と呼ぶことになる。
 */
export const 収めるの呼び名 = {
  /** 縦横とも器に収める場所 (拡大表示) */
  両方: "収める",
  /** 幅にだけ合わせる場所 (並べて見る側) */
  幅だけ: "幅に合わせる",
} as const;

/** 刻みの値とみなす誤差。 ホイールで動かした値が刻みにちょうど重なった時に、同じ刻みへ留まらせない */
const 刻みの誤差 = 1e-6;

/**
 * 刻みを 1 つ動かした先。 端では動かない。
 *
 * **刻みの外の値からは、その向きで次にある刻みへ動く** (#1961)。 ホイールで 1.23 倍にした後に
 * 「上げる」 を押すと 1.5 倍、「下げる」 を押すと 1 倍へ行く。
 *
 * `収める` から動かす時の起点は、器に収めて実際に描かれている倍率 (`収めた倍率`) を渡されれば
 * それにする。 画面を測れない時は **実寸 (1 倍) を起点にする** = 起点が判らないまま動かすと、
 * 押した時の動きが図ごとに変わる。
 *
 * その向きに刻みが無ければ **動かない** (起点を返す)。 器に収めた倍率が刻みの外 (0.31 倍や 4 倍) の時に、
 * 「下げる」 で刻みの端 (0.5 倍) へ跳ねて逆に大きくなるのを避ける。
 *
 * 数として読めない値 (`NaN` / 無限) は実寸へ戻す。 状態が壊れた時に押しても動かなくなるのを避ける。
 */
export const 次の倍率 = (
  いま: 倍率の指定,
  向き: "上げる" | "下げる",
  収めた倍率?: number,
): 倍率の指定 => {
  const 起点 = 起点の倍率(いま, 収めた倍率);
  if (!Number.isFinite(起点)) return 1;
  const 次 =
    向き === "上げる"
      ? 倍率の刻み.find((刻み) => 刻み > 起点 + 刻みの誤差)
      : [...倍率の刻み].reverse().find((刻み) => 刻み < 起点 - 刻みの誤差);
  return 次 ?? 起点;
};

/** `収める` を数値の倍率に読み替える。 測れていなければ実寸 */
const 起点の倍率 = (いま: 倍率の指定, 収めた倍率: number | undefined): number => {
  if (いま !== 収める) return いま;
  return 測れた倍率か(収めた倍率) ? 収めた倍率 : 1;
};

const 測れた倍率か = (値: number | undefined): 値 is number =>
  値 !== undefined && Number.isFinite(値) && 値 > 0;

/** 端に居て、その向きへはもう動かせないか。 */
export const 端か = (いま: 倍率の指定, 向き: "上げる" | "下げる", 収めた倍率?: number): boolean =>
  次の倍率(いま, 向き, 収めた倍率) === 起点の倍率(いま, 収めた倍率);

/** ホイール 1 回で数える `deltaY` の上限 (画素)。 理由は `ホイールで動かした倍率` */
export const ホイール1回の上限 = 25;

/** `deltaY` 1 画素あたりの倍率の変わり方 (指数の係数) */
const ホイールの効き = 0.008;

/**
 * ホイールやつまみ操作で動かした先の倍率 (#1961)。
 *
 * 1 回の `wheel` の `deltaY` (画素に直した値) に比例して **掛け算で** 動かす。 足し算にすると、
 * 小さい倍率ほど 1 回の変化が相対的に大きくなり、縮めた図が急に消える。 上向き (`deltaY` が負) で拡大。
 *
 * **1 回で動く量に上限を置く** (`ホイール1回の上限`)。 マウスのホイール 1 目盛は `deltaY` が 100 前後で、
 * トラックパッドのつまみは 1 回が 1〜10 と桁が違う。 比例のままでは、つまみに合わせた係数だと 1 目盛で
 * 図が 2 倍を超えて跳ね、ホイールに合わせるとつまみが鈍くなる。 上限で揃えると 1 目盛が約 1.22 倍、
 * つまみは指の開きにほぼ沿って動く。
 *
 * 動かせる範囲は刻みの両端までだが、**いまの倍率が既に範囲の外なら、そこから外へは動かさず内へだけ動かす**。
 * 器に収めた倍率が 0.31 倍の図を縮める向きに回した時、下限の 0.5 倍へ跳ねて大きくなるのを避ける。
 */
export const ホイールで動かした倍率 = (いま: number, deltaY: number): number => {
  if (!測れた倍率か(いま) || !Number.isFinite(deltaY)) return いま;
  const 量 = Math.min(ホイール1回の上限, Math.max(-ホイール1回の上限, deltaY));
  const 次 = いま * Math.exp(-量 * ホイールの効き);
  const 下限 = Math.min(倍率の下限, いま);
  const 上限 = Math.max(倍率の上限, いま);
  return Math.min(上限, Math.max(下限, 次));
};

/** 1 次元の区間。 画面の上の図の位置 (`left` / `top`) と長さ (`width` / `height`) */
export type 区間 = { 位置: number; 長さ: number };

/**
 * 倍率を変えた後、カーソルの下にあった図の点を同じ画面の位置へ戻すための巻き取りの差 (#1961)。
 *
 * 前の図の中でカーソルが占める割合を求め、後の図で同じ割合の点が画面のどこへ行ったかを見る。
 * 返り値をそのまま器の `scrollLeft` / `scrollTop` に足す。 図が器の中で中央に寄せられていても
 * (位置が倍率で変わっても) 同じ式で戻せる。
 *
 * 前の長さが 0 以下の時は割合を出せないので 0 を返す (動かさない)。
 */
export const カーソルの下を残す差 = (前: 区間, 後: 区間, カーソル: number): number => {
  if (!(前.長さ > 0) || !Number.isFinite(後.長さ)) return 0;
  const 割合 = (カーソル - 前.位置) / 前.長さ;
  return 後.位置 + 割合 * 後.長さ - カーソル;
};

/** 倍率を測れていない時に欄へ出す文字列。 数字の代わりに線を置き、単位だけ残す */
export const 測れていない倍率の表示 = "--%";

/**
 * 操作部品に出す文字列。 **どの状態でも百分率の形で出す** (#1961)。
 *
 * 以前は器に収めている時に「幅に合わせる」 を出しており、隣の同じ名前のボタンと語が 2 つ並んで、
 * 今の倍率が読めなかった。 器に収めている時は、実際に描かれている倍率 (`収めた倍率`) を出す。
 *
 * 測れない時 (図がまだ描かれていない / 描けない図) は `測れていない倍率の表示` を出す。
 * 0% や 100% に潰すと、測っていない値を倍率として見せることになる。 呼び名に戻すと語がまた重なる。
 */
export const 倍率の表示 = (いま: 倍率の指定, 収めた倍率?: number): string => {
  if (いま !== 収める) {
    return Number.isFinite(いま) ? `${Math.round(いま * 100)}%` : 測れていない倍率の表示;
  }
  return 測れた倍率か(収めた倍率) ? `${Math.round(収めた倍率 * 100)}%` : 測れていない倍率の表示;
};

/**
 * 倍率を指定した時に svg へ与える幅 (px)。 viewBox の 1 world を 1px として数える。
 *
 * `収める` の時と、幅を出せない時 (0 / 負値 / 非有限) は `undefined` を返す。
 * 0 に潰さない = 0 を返すと図が消えるが、それは「収める」 とも「拡げる」 とも違う状態になる。
 */
export const svgの幅 = (いま: 倍率の指定, viewBoxの幅: number | undefined): number | undefined => {
  if (いま === 収める) return undefined;
  if (viewBoxの幅 === undefined || !Number.isFinite(viewBoxの幅) || viewBoxの幅 <= 0) return undefined;
  return viewBoxの幅 * いま;
};
