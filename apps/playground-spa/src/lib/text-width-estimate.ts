/**
 * 字の塊の横幅の見積り (#1678)。
 *
 * 見本の図で「字が重なっていないか」 を数える検査が使う。 描いた SVG は幅を持たない
 * (`jsdom` も静止した書き出しも実寸を返さない) ので、字数と級から見積もる。
 *
 * ## 狭い側に外してはいけない
 *
 * 重なりを数える検査は **0 件を期待する**。 見積りが実物より狭いと、重なっていても
 * 幅を狭く見て重なりとして数えず、そのまま偽の合格になる。 陽性の入力も陰性対照も
 * 植え込み対照もこの向きの誤りを見つけられない = どれも探し方の側しか見ていない。
 *
 * 実際に円グラフの検査は半角を 0.55 で見ていた。 描画側の実測は 0.86 で **3 割狭い**。
 * 縦にほどく円では答えが変わらなかったが、横に詰める半円ゲージでは 12 件の重なりを
 * 1 件も見つけられない側に倒れる。
 *
 * ## 係数は描画側と同じ値を使う
 *
 * 係数は書体の実測値 (`canvas` の `measureText` を 100px で当てた値) で、割付の判断では
 * ない。 書体が変われば描画側と検査側が同時に誤りになるので、二重管理にならない。
 * 箱幅 / 余白 / 級のような「描画側が決めた値」 は写さない (版を上げた時に片方だけ古くなる)。
 *
 * 階級は 4 つ。 広い字と細い字はどちらも ASCII なので、ASCII の外がそこに当たることはない。
 */

/** 広い字 (`W` が最大で 1.038) */
const 広い = "W@%Mm";
/** 細い字 (`;` が最大で 0.343) */
const 細い = "ijlI.,:;'! ";

/** 字 1 つが級に対して占める幅の比 */
function 比(c: string): number {
  if (細い.includes(c)) return 0.37;
  if (広い.includes(c)) return 1.04;
  // ASCII の外は分類しない = 最大の比で見積もれば必ず実物以上になる (和文の実測は 1.000)
  return (c.codePointAt(0) ?? 0) < 128 ? 0.86 : 1.04;
}

/** 字の塊の横幅の見積り */
export function 字幅(文: string, 級: number): number {
  return [...文].reduce((w, c) => w + 比(c) * 級, 0);
}
