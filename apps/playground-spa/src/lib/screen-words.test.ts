/**
 * 待つ宣言のうち古くなったものを返す (#1930)。 本番と植え込み対照が同じ関数を使う。
 *
 * 古くなり方は 3 つ = file が消えた / 理由が Issue を指さない / 戻しても一覧の外の語が出ない
 * (待っていた Issue が片付いたのに宣言だけが残った)。
 */
function 待つ宣言の難(宣言: Record<string, string>, 候補: string[] = 画面のfile()): string[] {
  const out: string[] = [];
  for (const [file, 理由] of Object.entries(宣言)) {
    const files = 候補.filter((f) => f.slice(f.lastIndexOf("/") + 1) === file);
    if (files.length !== 1) {
      out.push(`${file}: 画面の file に 1 つだけ居ない (${files.length} 件)`);
      continue;
    }
    if (!/#\d+/.test(理由)) out.push(`${file}: 待つ理由が Issue の番号を持たない`);
    // 名前の file は名前を足した形で戻す = 名前は走査ではなく `見本の名前()` から入る
    const 戻した = file === 見本の名前のfile
      ? 画面に出る字たち(files).字.flatMap((s) => 残るカタカナ語(s))
      : 画面の枠に残るカタカナ語(files).語.map((x) => x.語);
    if (戻した.length === 0) out.push(`${file}: 戻しても判定が赤くならない (待つ理由が残っていない。 宣言を消す)`);
  }
  return out;
}
