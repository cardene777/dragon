/** 相対 path が、宣言 (既定は本番の `カタカナの判定を待つ材料`) で判定を待つ材料か */
function 判定を待つ材料(f: string, 宣言: Record<string, string> = カタカナの判定を待つ材料): boolean {
  return Object.hasOwn(宣言, f.slice(f.lastIndexOf("/") + 1));
}

/**
 * 画面の字に残る、残してよいカタカナ語の外の語 (#1854)。
 *
 * 母集団は英語の判定と同じ file から、カタカナ語の判定を待つ材料を外したもの。
 * **見本の名前は、名前の file が判定を待っていない時だけ足す** (#1930)。 名前は走査ではなく
 * `見本の名前()` から入るので、file を外すだけでは名前が母集団に残る。 file を名指しした時は
 * 足さない = 植え込み対照が一時 file の字だけを見られるようにする。
 *
 * 語ごとに出た字を 1 つ添えて返す = 落ちた時にどこを直すかを読み手が探さずに済む。
 *
 * 宣言を引数で受ける = 植え込み対照が「待つ宣言を持つ形」 を本番と同じ組み方に通すため。
 */
function 画面の枠に残るカタカナ語(
  files?: string[],
  宣言: Record<string, string> = カタカナの判定を待つ材料,
): {
  語: { 語: string; 字: string }[];
  走査: number;
  全字: string[];
} {
  const { 字, 走査 } = 画面に出る字たち(files ?? 画面のfile().filter((f) => !判定を待つ材料(f, 宣言)), {
    見本の名前を足す: files === undefined && !Object.hasOwn(宣言, 見本の名前のfile),
  });
  const 最初の字 = new Map<string, string>();
  for (const s of 字) {
    for (const w of 残るカタカナ語(s)) if (!最初の字.has(w)) 最初の字.set(w, s);
  }
  return { 語: [...最初の字].map(([語, s]) => ({ 語, 字: s })), 走査, 全字: 字 };
}

