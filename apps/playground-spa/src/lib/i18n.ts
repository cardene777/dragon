/**
 * catalog item の英語表示名を返す。 未登録は英語 export name をそのまま返す (fallback)。
 */
export function itemNameEn(exportName: string): string {
  return ITEM_NAME_EN[exportName] ?? exportName;
}

/** locale に応じた catalog item の表示名。 */
export function itemName(exportName: string, locale: Locale): string {
  return locale === "ja" ? itemNameJa(exportName) : itemNameEn(exportName);
}
