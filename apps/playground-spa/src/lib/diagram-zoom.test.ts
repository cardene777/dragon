/**
 * 図の倍率の検査 (#1745 / #1749)。
 *
 * 画面を描かずに確かめられる形にしてあるので、ここでは刻みの動き方と呼び名だけを固定する。
 * 実際に svg がその幅で描かれることは `tests/catalog-modal-zoom.spec.ts` と
 * `tests/catalog-inline-zoom.spec.ts` が見る。
 */
import { describe, it, expect } from "vitest";
import {
  倍率の刻み,
  倍率の下限,
  倍率の上限,
  収める,
  収めるの呼び名,
  次の倍率,
  端か,
  ホイールで動かした倍率,
  ホイール1回の上限,
  カーソルの下を残す差,
  倍率の表示,
  測れていない倍率の表示,
  svgの幅,
} from "./diagram-zoom";

describe("図の倍率 (#1745 / #1749)", () => {
  it("刻みが 1 つ以上あり、昇順で重複が無い (空振り防止)", () => {
    expect(倍率の刻み.length, "刻みが空 (検査が空振りしている)").toBeGreaterThan(0);
    expect([...倍率の刻み].sort((a, b) => a - b)).toEqual([...倍率の刻み]);
    expect(new Set(倍率の刻み).size).toBe(倍率の刻み.length);
  });

  it("実寸 (1 倍) が刻みに入っている", () => {
    // `収める` からの起点なので、無いと押した時の行き先が決まらない
    expect(倍率の刻み).toContain(1);
  });

  it("`収める` から上げると、実寸の 1 つ上へ行く", () => {
    const 実寸の上 = 倍率の刻み[倍率の刻み.indexOf(1) + 1];
    expect(次の倍率(収める, "上げる")).toBe(実寸の上);
  });

  it("`収める` から下げると、実寸の 1 つ下へ行く", () => {
    const 実寸の下 = 倍率の刻み[倍率の刻み.indexOf(1) - 1];
    expect(次の倍率(収める, "下げる")).toBe(実寸の下);
  });

  it("刻みを 1 つずつ辿れる", () => {
    const 上り: number[] = [];
    let いま = 倍率の刻み[0]!;
    for (let i = 0; i < 倍率の刻み.length + 2; i += 1) {
      上り.push(いま);
      いま = 次の倍率(いま, "上げる") as number;
    }
    // 端に着いたら同じ値が続く = 一意にすると刻みそのものになる
    expect([...new Set(上り)]).toEqual([...倍率の刻み]);
  });

  it("端では動かない", () => {
    const 下端 = 倍率の刻み[0]!;
    const 上端 = 倍率の刻み[倍率の刻み.length - 1]!;
    expect(次の倍率(下端, "下げる")).toBe(下端);
    expect(次の倍率(上端, "上げる")).toBe(上端);
    expect(端か(下端, "下げる")).toBe(true);
    expect(端か(上端, "上げる")).toBe(true);
    // 反対向きには動く = `端か` が何にでも true を返す形ではない
    expect(端か(下端, "上げる")).toBe(false);
    expect(端か(上端, "下げる")).toBe(false);
  });

  it("刻みの外の倍率からは、その向きで次にある刻みへ動く (#1961)", () => {
    // ホイールで細かく動かした後にボタンを押した時、実寸へ跳ね戻さない
    expect(次の倍率(1.23, "上げる")).toBe(1.5);
    expect(次の倍率(1.23, "下げる")).toBe(1);
    expect(次の倍率(0.6, "下げる")).toBe(0.5);
    expect(次の倍率(2.9, "上げる")).toBe(3);
    // 刻みにほぼ重なった値は、同じ刻みに留まらず隣へ動く
    expect(次の倍率(1.0000000001, "上げる")).toBe(1.5);
    expect(次の倍率(1.4999999999, "下げる")).toBe(1);
  });

  it("その向きに刻みが無ければ動かない (刻みの端へ跳ねない) (#1961)", () => {
    // 0.31 倍から「下げる」 で 0.5 倍へ行くと、押した向きと逆に大きくなる
    expect(次の倍率(0.31, "下げる")).toBe(0.31);
    expect(端か(0.31, "下げる")).toBe(true);
    expect(次の倍率(0.31, "上げる")).toBe(0.5);
    expect(端か(0.31, "上げる")).toBe(false);
    expect(次の倍率(4, "上げる")).toBe(4);
    expect(次の倍率(4, "下げる")).toBe(3);
  });

  it("数として読めない倍率は実寸へ戻す", () => {
    // 状態が壊れた時に押しても動かなくなるのを避ける
    for (const 値 of [Number.NaN, Number.POSITIVE_INFINITY, Number.NEGATIVE_INFINITY]) {
      expect(次の倍率(値, "上げる"), `${String(値)} から上げる`).toBe(1);
      expect(次の倍率(値, "下げる"), `${String(値)} から下げる`).toBe(1);
    }
  });

  it("器に収めた倍率を渡されたら、`収める` からの起点をそれにする (#1961)", () => {
    // 並べて見る側で 0.62 倍に描かれている図を「上げる」 と、実寸の上 (1.5 倍) ではなく 0.75 倍へ行く
    expect(次の倍率(収める, "上げる", 0.62)).toBe(0.75);
    expect(次の倍率(収める, "下げる", 0.62)).toBe(0.5);
    expect(次の倍率(収める, "上げる", 1.7)).toBe(2);
    expect(次の倍率(収める, "下げる", 1.7)).toBe(1.5);
    // 測れていない値は渡されなかったのと同じ (実寸を起点にする)
    for (const 値 of [0, -1, Number.NaN, undefined]) {
      expect(次の倍率(収める, "上げる", 値), `収めた倍率 ${String(値)}`).toBe(1.5);
    }
    expect(端か(収める, "下げる", 0.4)).toBe(true);
    expect(端か(収める, "上げる", 0.4)).toBe(false);
  });

  it("ホイールは掛け算で動かし、上向きで拡大・下向きで縮小する (#1961)", () => {
    const 上 = ホイールで動かした倍率(1, -100);
    const 下 = ホイールで動かした倍率(1, 100);
    expect(上).toBeGreaterThan(1);
    expect(下).toBeLessThan(1);
    // 掛け算 = 同じ量を上下に回すと元へ戻る (足し算だと小さい倍率ほど 1 回で大きく動く)
    expect(ホイールで動かした倍率(上, 100)).toBeCloseTo(1, 10);
    expect(ホイールで動かした倍率(0.8, 100) / 0.8).toBeCloseTo(
      ホイールで動かした倍率(2, 100) / 2,
      10,
    );
    // 回さなければ動かない
    expect(ホイールで動かした倍率(1.23, 0)).toBe(1.23);
  });

  it("ホイール 1 回で動く量には上限があり、それより小さい量には比例する (#1961)", () => {
    // マウスの 1 目盛 (100) と大きく回した 1 回 (1000) は同じだけ動く = 1 目盛で跳ねない
    expect(ホイールで動かした倍率(1, 100)).toBe(ホイールで動かした倍率(1, ホイール1回の上限));
    expect(ホイールで動かした倍率(1, -1000)).toBe(ホイールで動かした倍率(1, -ホイール1回の上限));
    // 1 目盛で 1.1 倍より大きく 1.5 倍より小さく動く (鈍すぎず、刻み 1 つ分を超えない)
    const 一目盛 = ホイールで動かした倍率(1, -100);
    expect(一目盛).toBeGreaterThan(1.1);
    expect(一目盛).toBeLessThan(1.5);
    // つまみの小さい量は比例する = 2 回分と 1 回で 2 倍の量が同じ所へ着く
    expect(ホイールで動かした倍率(ホイールで動かした倍率(1, -4), -4)).toBeCloseTo(
      ホイールで動かした倍率(1, -8),
      10,
    );
    expect(ホイールで動かした倍率(1, -4)).toBeLessThan(ホイールで動かした倍率(1, -8));
  });

  it("ホイールは刻みの両端より外へ動かさない (#1961)", () => {
    expect(ホイールで動かした倍率(2.9, -10_000)).toBe(倍率の上限);
    expect(ホイールで動かした倍率(0.6, 10_000)).toBe(倍率の下限);
    expect(倍率の下限).toBe(倍率の刻み[0]);
    expect(倍率の上限).toBe(倍率の刻み[倍率の刻み.length - 1]);
  });

  it("範囲の外に居る時は、外へは動かさず内へだけ動かす (#1961)", () => {
    // 器に収めて 0.31 倍の図を縮める向きに回しても、0.5 倍へ跳ねて大きくならない
    expect(ホイールで動かした倍率(0.31, 100)).toBe(0.31);
    expect(ホイールで動かした倍率(0.31, -100)).toBeGreaterThan(0.31);
    expect(ホイールで動かした倍率(4, -100)).toBe(4);
    expect(ホイールで動かした倍率(4, 100)).toBeLessThan(4);
  });

  it("ホイールに読めない値が来たら倍率を変えない", () => {
    expect(ホイールで動かした倍率(1.5, Number.NaN)).toBe(1.5);
    expect(ホイールで動かした倍率(Number.NaN, -100)).toBeNaN();
    expect(ホイールで動かした倍率(0, -100)).toBe(0);
  });

  it("カーソルの下の点を同じ画面の位置へ戻す巻き取りの差を出す (#1961)", () => {
    // 左端 100px から幅 400px の図の、左から 1/4 (200px) にカーソル。 2 倍にすると幅 800px になり、
    // 同じ点は 100 + 200 = 300px へ行く = 100px 巻き取れば 200px に戻る
    expect(カーソルの下を残す差({ 位置: 100, 長さ: 400 }, { 位置: 100, 長さ: 800 }, 200)).toBe(100);
    // 縮めた時は負の差 (手前へ巻き戻す)
    expect(カーソルの下を残す差({ 位置: 100, 長さ: 800 }, { 位置: 100, 長さ: 400 }, 300)).toBe(
      -100,
    );
    // 図が中央寄せで位置も動いた場合 (器 1000px の中央に 400px → 800px)
    expect(カーソルの下を残す差({ 位置: 300, 長さ: 400 }, { 位置: 100, 長さ: 800 }, 500)).toBe(0);
    // 倍率が変わらなければ差は 0
    expect(カーソルの下を残す差({ 位置: 30, 長さ: 500 }, { 位置: 30, 長さ: 500 }, 222)).toBe(0);
  });

  it("前の図の長さが測れなければ巻き取らない", () => {
    expect(カーソルの下を残す差({ 位置: 0, 長さ: 0 }, { 位置: 0, 長さ: 800 }, 200)).toBe(0);
    expect(カーソルの下を残す差({ 位置: 0, 長さ: Number.NaN }, { 位置: 0, 長さ: 800 }, 200)).toBe(
      0,
    );
    expect(カーソルの下を残す差({ 位置: 0, 長さ: 400 }, { 位置: 0, 長さ: Number.NaN }, 200)).toBe(
      0,
    );
  });

  it("倍率を指定している時の表示は百分率", () => {
    expect(倍率の表示(1)).toBe("100%");
    expect(倍率の表示(0.75)).toBe("75%");
    expect(倍率の表示(3)).toBe("300%");
    // ホイールで動かした刻みの外の値も四捨五入した百分率
    expect(倍率の表示(1.234)).toBe("123%");
  });

  it("`収める` の呼び名は場所ごとに違う", () => {
    // 拡大表示は縦横とも収めるが、並べて見る側は幅にだけ合わせる。 同じ言葉にすると、
    // 細い図が 1.7 倍に伸びるのを「収める」 と呼ぶことになる
    // 呼び名は 2 つとも空でなく、互いに違う (同じなら場所を分ける意味が無い)
    // 2 言語とも見る (#2453)。 片方だけ見ると、英語を足し忘れた時に緑のまま通る
    for (const 言語 of ["ja", "en"] as const) {
      expect(収めるの呼び名.両方[言語].trim(), 言語).not.toBe("");
      expect(収めるの呼び名.幅だけ[言語].trim(), 言語).not.toBe("");
      expect(収めるの呼び名.両方[言語], 言語).not.toBe(収めるの呼び名.幅だけ[言語]);
    }
  });

  it("器に収めている時も、描かれている倍率を百分率で出す (#1961)", () => {
    // 隣のボタン (幅に合わせる / 収める) と同じ語を欄に出すと、今の倍率が読めない
    expect(倍率の表示(収める, 0.62)).toBe("62%");
    expect(倍率の表示(収める, 1.7)).toBe("170%");
  });

  it("測れていない倍率は数字に潰さず、呼び名にも戻さない (#1961)", () => {
    const 呼び名 = Object.values(収めるの呼び名).flatMap((x) => [x.ja, x.en]);
    expect(呼び名.length, "呼び名が 1 つも無い (検査が空振りしている)").toBeGreaterThan(0);
    for (const 値 of [0, -1, Number.NaN, undefined]) {
      const 表示 = 倍率の表示(収める, 値);
      expect(表示, `収めた倍率 ${String(値)}`).toBe(測れていない倍率の表示);
      expect(呼び名, `収めた倍率 ${String(値)} で呼び名が出る`).not.toContain(表示);
    }
    expect(倍率の表示(Number.NaN)).toBe(測れていない倍率の表示);
    // 測れていない時の文字も `%` で終わり、数字を含まない (0% や 100% を装わない)
    expect(測れていない倍率の表示.endsWith("%")).toBe(true);
    expect(測れていない倍率の表示).not.toMatch(/\d/);
  });

  it("svg の幅は viewBox の幅 × 倍率", () => {
    expect(svgの幅(1, 2190)).toBe(2190);
    expect(svgの幅(2, 2190)).toBe(4380);
    expect(svgの幅(0.5, 2190)).toBe(1095);
  });

  it("`収める` と、幅を出せない時は幅を返さない (0 に潰さない)", () => {
    expect(svgの幅(収める, 2190)).toBeUndefined();
    for (const 幅 of [0, -1, Number.NaN, Number.POSITIVE_INFINITY, undefined]) {
      expect(svgの幅(1, 幅), `幅 ${String(幅)} で undefined 以外が返る`).toBeUndefined();
    }
  });
});
