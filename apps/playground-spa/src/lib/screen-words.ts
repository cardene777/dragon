/**
 * 字の中のカタカナの連なりを返す (#1855)。
 *
 * 2 文字以上を 1 語とする = 1 文字のカタカナ (`ト` / `プ`) は語ではなく、拾うと
 * 助詞混じりの字が大量に当たる。 長音符は連なりの中でだけ認める (`サーバー` で 1 語、
 * 先頭の `ー` は語の始まりにしない)。
 *
 * **正規表現ではなく関数で配る**。 `g` を付けた正規表現を配ると、`test()` で使った側が
 * 次回の探し始めをずらす (`lastIndex` が残る)。 呼ぶ側がその落とし穴を知らずに済む形にする。
 *
 * 引き手は 2 つで、**許す語の一覧はそれぞれが持つ** = 見る相手が違う
 * (カタログの分類の呼び名は #1805 の 2 語、画面の字は #1854 の判断待ち)。
 * 揃えるのは「何をカタカナ語と読むか」 までで、そこから先は相手ごとに決まる。
 */
export function カタカナの連なり(文: string): string[] {
  return [...文.matchAll(/[ァ-ヴ][ァ-ヴー]+/g)].map((m) => m[0]);
}

