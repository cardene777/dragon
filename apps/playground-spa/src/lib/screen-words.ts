/** 字のうち、2 通りの呼び名が残っている対を返す */
export function 二通りの呼び名(文: string): string[] {
  return 揃える呼び名
    .filter((対) => 文.includes(対.直す))
    .map((対) => `${対.直す} → ${対.揃える先}`);
}
