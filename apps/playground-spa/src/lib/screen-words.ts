/** file 名 (`CONTRIBUTING.md`)。 語に割らずそのまま通す */
const file名 = /[A-Za-z][A-Za-z0-9_.-]*\.(?:md|json|ts|tsx|yml|yaml|svg|png)\b/g;

/**
 * 斜線でつないだ名前 (`/editor` / `feature/<番号>-<短い説明>`)。 同じくそのまま通す。
 *
 * 読み手が画面のとおりに打ち込む相手なので、訳すと打てなくなる。
 * 語の区切りに使う斜線 (`不具合 / 提案` のように前後に空白がある形) は当たらない。
 */
const 斜線を含む名 = /[A-Za-z0-9_.-]*\/[^\s]*/g;

/** 版の番号 (`v0.5`)。 数を含む 1 つの名前で、語に割ると `v0` が残る */
const 版の番号 = /\bv\d+(?:\.\d+)*\b/g;

/**
 * 語の切り出し。 **繋ぎの横棒を語に含める**。
 *
 * `alarm-clock` / `double-click` は記法の項目の値で 1 語。 横棒を切れ目にすると
 * `alarm` と `clock` に割れ、実物に無い語を咎めることになる。
 */
const 英単語 = /[A-Za-z][A-Za-z0-9_-]*/g;

/**
 * 規格の名前は番号と組で 1 つの固有名詞 (`ERC-20` / `EIP-1559` / `ERC-4337`)。
 * 番号は規格ごとに変わるので一覧に並べず、落としてから一覧を引く。
 */
export function 番号を落とす(語: string): string {
  return 語.replace(/-\d+$/, "");
}

/**
 * 字のうち、残してよい語に無い英字 2 文字以上の語。 3 つの検査が同じ関数を使う。
 *
 * 日本語を含むかどうかは見ない = 呼ぶ側が「画面に出る字」 を決めてから渡す
 * (英語だけの札を咎める検査もこの関数を使う)。
 */
export function 残る英単語(字: string): string[] {
  const 素 = 字.replace(file名, " ").replace(斜線を含む名, " ").replace(版の番号, " ");
  return [...new Set(素.match(英単語) ?? [])].filter(
    (w) => w.length >= 2 && !(w in 残してよい語) && !(番号を落とす(w) in 残してよい語),
  );
}

