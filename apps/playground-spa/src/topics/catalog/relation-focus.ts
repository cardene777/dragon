/**
 * 順番を持たない図を「触れて読む」 形にする (#1757)。
 *
 * クラス図と ER 図は箱と箱の関係が **同時に** 成り立っている。 線を 1 本ずつ引く動きは
 * 作り手が決めた読ませ方でしかなく、読み手の問い (この箱はどこと繋がっているか) には
 * 答えない。
 *
 * 2 つを併せて入れる。
 *
 * | 指定 | 何が変わるか |
 * |---|---|
 * | `relationFocus: "hover"` | 箱に触れると その箱 ・ 繋がる線 ・ 相手の箱だけが光る |
 * | `edgeReveal: "all"` | 線を最初から全部出す = 段は引くのをやめて光らせるだけになる |
 *
 * **段は消さない**。 段の説明文 (「白抜きの三角。 三角は親の側に付く。」 等) は記法の解説
 * そのもので、触れる操作では運べない。 2 つ目を併せて入れることで、読み手が嫌っていた
 * 「線が 1 本ずつ引かれる動き」 だけが消えて説明は残る。
 */
import type { CdlDiagram } from "@cardenelabs/cdl";

/** 触れて読む図にする。 対象は順番を持たない図 (クラス図 / ER 図) に限る */
export const 触れて読む = (d: CdlDiagram): CdlDiagram => ({
  ...d,
  relationFocus: "hover",
  edgeReveal: "all",
});
