// @vitest-environment node
/**
 * 図の説明 (`topics/catalog/*.cdl.ts` の `subtitle__*`) に英語を残さない検査。
 *
 * 説明は見本帳の一覧と拡大の窓に出る (`CategoryPage.tsx` が描く) が、
 * **画面の字の英語の判定からは外れている** (`topics/` は記法そのものを持つので置き場ごと外している)。
 * そのため説明の英語とカタカナ語だけをここで見る。
 *
 * | 何を | どこが見るか | どう見るか | 経緯 |
 * |---|---|---|---|
 * | 英語 | この file | 0 件 | #1830 で天井を置き、#1829 で説明を日本語に書き直して 0 にした |
 * | カタカナ語 | この file | 天井 | #1857 で天井を置いた。 残る語は同じ図の箱の題が使う |
 * | 2 通りの呼び名 | `lib/screen-words.test.ts` | 0 件 | `topics/` を呼び名の母集団から外していないので、説明もそちらが見る |
 *
 * **判定は自前で持たない** = 画面の字の判定 (`残る英単語()`、#1817 で 1 つに寄せた) と
 * 記法が知る名前 (#1827 の 4 経路) をそのまま引く。
 * 一覧に語を足した日に、この検査も同じ向きに動く。
 */
import { describe, it, expect } from "vitest";
import { readdirSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { 残る英単語, カタカナの連なり } from "@/lib/screen-words";
import { 記法が知る名前, 綴りの照合 } from "@/lib/notation-names";

const 見本の置き場 = fileURLToPath(new URL("./catalog/", import.meta.url));

/**
 * 同じ説明に残るカタカナ語の天井 (#1857)。
 *
 * 英語だけに天井が置かれていて、**カタカナはどちらの検査から見ても外側に落ちていた** =
 * 画面の字の側 (#1855) は `topics/` を丸ごと母集団から外しており、こちらは英語しか数えて
 * いなかった。
 *
 * #1829 で説明を書き直した後に残る語 (`サーバー` / `テスト` / `ブロック` など) は、
 * どれも同じ図の箱の題か値の名前が使う語で、説明だけを開くと図と呼び名が食い違う。
 * 開くなら図の中の字と同時に開く (画面のカタカナ語の判断は #1854 が持つ)。
 *
 * **減った時も落とす** = 下回ったまま通すと、一度開いた分がまた増えても気付けない
 * (天井が緩みっぱなしになる)。 落ちた時の文で下げる先の数を出す。
 */
const カタカナの天井 = { 説明: 10, 語: 9, 延べ: 12 };

/**
 * 図の説明を集める。
 *
 * `宣言` と `読めた` を分けて返すのは、**書き方が変わった日に気付くため**。
 * 値が複数行に分かれる形に変えると `読めた` だけが減り、差が出る。
 */
function 図の説明(): { 件: { file: string; 鍵: string; 文: string }[]; 宣言: number; file数: number } {
  const 件: { file: string; 鍵: string; 文: string }[] = [];
  let 宣言 = 0;
  let file数 = 0;
  for (const f of readdirSync(見本の置き場)) {
    if (!f.endsWith(".cdl.ts")) continue;
    file数 += 1;
    const s = readFileSync(見本の置き場 + f, "utf8");
    宣言 += [...s.matchAll(/export const subtitle__/g)].length;
    for (const m of s.matchAll(/export const subtitle__(\w+)\s*(?::\s*string\s*)?=\s*\n?\s*"([^"\\]*)"/g)) {
      件.push({ file: f, 鍵: m[1]!, 文: m[2]! });
    }
  }
  return { 件, 宣言, file数 };
}

/**
 * 説明 1 件に残る「開くべき英語」。
 *
 * 一覧が許す語 (`残る英単語()` が落とす) でも、記法が知る綴り (#1827) でもない語。
 * 記法の綴りを外すのは、それが **打ち込む字で訳せない** ため (#1825 と同じ線引き)。
 */
function 開くべき英語(文: string, 経路: Map<string, Set<string>>): string[] {
  const 残る = 残る英単語(文);
  return 綴りの照合(残る.map((w) => ({ 元: w, 綴り: w })), 経路).無い;
}

/**
 * 開くべき英語を含む説明と、語の種類と、延べの回数を数える。
 *
 * 期待する値は 3 つとも 0 で、落ちた時に「どの説明に何の語が残るか」 を出すために
 * 説明ごとの内訳を返す。
 *
 * **日本語を含まない説明も数える**。 天井を置いていた間は日本語の字を含む説明だけを見ており、
 * 英語だけで書いた説明は 1 語も数えていなかった (#1829)。 0 件を期待する形でこの穴を残すと、
 * 英語だけの説明を足した日にそのまま通る。
 */
function 数える(
  件: { file: string; 鍵: string; 文: string }[],
  経路: Map<string, Set<string>>,
): { 説明: { 鍵: string; 語: string[] }[]; 語: string[]; 延べ: number } {
  const 説明: { 鍵: string; 語: string[] }[] = [];
  const 語 = new Set<string>();
  let 延べ = 0;
  for (const r of 件) {
    const w = 開くべき英語(r.文, 経路);
    if (w.length === 0) continue;
    説明.push({ 鍵: r.鍵, 語: w });
    延べ += w.length;
    for (const x of w) 語.add(x);
  }
  return { 説明, 語: [...語], 延べ };
}

/**
 * 説明に残るカタカナ語を数える (#1857)。
 *
 * **何をカタカナ語と読むかは自前で持たない** = `lib/screen-words.ts` の
 * `カタカナの連なり()` を引く (#1855 で 1 つに寄せた)。 2 度書くと片方だけ直って食い違う。
 *
 * **拾い方そのものの境界は持ち主の検査が見る** (`lib/screen-words.test.ts`)。 ここの 3 つの数は
 * 件数しか見ないので、*語の中身が入れ替わっても件数が釣り合う* 形を捕まえられない
 * (変異で実測 = 長音符を連なりから外すと `メッセージ` が `メッセ` に化け、割れる語と消える語が
 * 相殺して 3 つとも動かなかった)。 同じ境界をここでもう一度書くと 2 度書きになるので、
 * **変異試験は 2 つの検査 file をまとめて回す** (`.context/scratch/katakana/mutate-1857.sh`)。
 *
 * 英語の側と同じく **3 つとも要る**。 説明の件数は「どれだけの説明が残っているか」、
 * 語の種類は「何通りの呼び名を決めないといけないか」、延べは「1 語ずつ足す形を止める」。
 * 延べが無いと、*既にカタカナを含む説明に既出の語を足す* 形が素通りする。
 */
function カタカナを数える(件: { 鍵: string; 文: string }[]): {
  説明: { 鍵: string; 語: string[] }[];
  語: string[];
  延べ: number;
  回数: Map<string, number>;
} {
  const 説明: { 鍵: string; 語: string[] }[] = [];
  const 回数 = new Map<string, number>();
  let 延べ = 0;
  for (const r of 件) {
    const w = カタカナの連なり(r.文);
    if (w.length === 0) continue;
    説明.push({ 鍵: r.鍵, 語: w });
    延べ += w.length;
    for (const x of w) 回数.set(x, (回数.get(x) ?? 0) + 1);
  }
  return { 説明, 語: [...回数.keys()], 延べ, 回数 };
}

describe("図の説明に英語を残さない (#1830 / #1829)", () => {
  it("開くべき英語を含む説明が 1 件も無い", () => {
    const { 件, 宣言, file数 } = 図の説明();
    const { 経路 } = 記法が知る名前();
    const { 説明, 語, 延べ } = 数える(件, 経路);
    console.log(
      `[図の説明] file=${file数} 宣言=${宣言} 読めた=${件.length}` +
        ` / 開くべき英語を含む説明=${説明.length} 語=${語.length} 種 延べ=${延べ} 回`,
    );
    // 0 件を期待するので、母集団が空でも通ってしまう。 走査の下限を先に確かめる
    expect(file数, "見本の file を 1 つも見ていない (検査が空振りしている)").toBeGreaterThan(5);
    expect(宣言, "説明の宣言を 1 件も見つけていない (検査が空振りしている)").toBeGreaterThan(100);
    expect(件.length, "説明の値を 1 件も読めていない (書き方が変わった)").toBe(宣言);
    expect(
      説明.map((r) => `${r.鍵}: ${r.語.join(" ")}`),
      "説明に英語が残っている。 図に見える物の呼び名 (縦列 / 箱 / 矢印 / 段 / つまみ / 部品) で書き直す。" +
        " 見せる機能の記法の綴りは、訳さずに括弧で添えてよい",
    ).toEqual([]);
  });

  it("開くべき英語を見つける (植え込み対照 + 対象外の対照)", () => {
    const { 経路 } = 記法が知る名前();
    // 植え込み対照 = 記法が知らない普通の英語を混ぜて、見つけること
    expect(開くべき英語("読む人が値を入れる pipeline の説明", 経路)).toEqual(["pipeline"]);
    // 対象外の対照 = 記法の綴りは打ち込む字なので咎めない
    expect(開くべき英語("readout で値を字に出す", 経路), "記法の綴りを咎めている").toEqual([]);
    expect(開くべき英語("signal を図へ繋ぐ", 経路)).toEqual([]);
    // 一覧が許す語も咎めない
    expect(開くべき英語("図は SVG として書き出せる", 経路)).toEqual([]);
    // 日本語だけの説明は 0 件
    expect(開くべき英語("読む人が値を入れる口の見本", 経路)).toEqual([]);
  });

  it("説明を 1 件も落とさずに走査している (収容対照)", () => {
    const { 件, file数 } = 図の説明();
    const files = new Set(件.map((r) => r.file));
    console.log(`[走査] ${[...files].map((f) => `${f}=${件.filter((r) => r.file === f).length}`).join(" ")}`);
    expect(file数, "見本の file を 1 つも見ていない").toBeGreaterThan(5);
    expect(files.size, "説明を持つ file が 1 つも無い (検査が空振りしている)").toBeGreaterThan(0);
    // 鍵が重複していない = 同じ説明を 2 度数えていない
    const 鍵 = 件.map((r) => r.鍵);
    expect(new Set(鍵).size, "同じ説明を 2 度数えている").toBe(鍵.length);
  });

  it("英語を含む説明を混ぜると数える (植え込み対照、本番と同じ数え方)", () => {
    // 0 件を期待する検査は、探し方が何も見つけない形に壊れても通る。
    // 本番と同じ `数える()` に違反を 1 件ずつ置いて、見つけることを確かめる
    const { 経路 } = 記法が知る名前();
    const 植えた = 数える([{ file: "a.cdl.ts", 鍵: "a", 文: "縦列に分けて pipeline で見せる" }], 経路);
    expect(植えた.説明.map((r) => r.鍵)).toEqual(["a"]);
    // **英語だけの説明も数える** = 天井を置いていた間は日本語を含む説明しか見ていなかった
    const 英語だけ = 数える([{ file: "a.cdl.ts", 鍵: "b", 文: "pipeline with three stages" }], 経路);
    expect(
      英語だけ.説明.map((r) => r.鍵),
      "英語だけで書いた説明を数えていない (日本語を含む説明だけを見る形に戻っている)",
    ).toEqual(["b"]);
    // 対象外の対照 = 書き直した後の形 (日本語 + 括弧で添えた記法の綴り) は数えない
    const 書き直した形 = 数える(
      [{ file: "a.cdl.ts", 鍵: "c", 文: "つまみで値を変え、値を見せる部品で出す (readout)" }],
      経路,
    );
    expect(書き直した形.説明, "記法の綴りを添えた説明を咎めている").toEqual([]);
  });
});


describe("図の説明に残るカタカナ語の歯止め (#1857)", () => {
  it("いまの天井を超えていない、下回ってもいない", () => {
    const { 件, 宣言, file数 } = 図の説明();
    const { 説明, 語, 延べ, 回数 } = カタカナを数える(件);
    const 多い = [...回数.entries()]
      .sort((a, b) => b[1] - a[1])
      .slice(0, 10)
      .map(([w, n]) => `${w}=${n}`);
    console.log(
      `[図の説明のカタカナ] file=${file数} 宣言=${宣言} 読めた=${件.length}` +
        ` / 含む説明=${説明.length} (天井 ${カタカナの天井.説明})` +
        ` 語=${語.length} 種 (天井 ${カタカナの天井.語})` +
        ` 延べ=${延べ} 回 (天井 ${カタカナの天井.延べ}) / 多い順 ${多い.join(" ")}`,
    );
    // 空振り防止 = 母集団が空だと 3 つの数がそろって 0 になり、天井の下回りで落ちる。
    // それでも走査の下限を置くのは、**落ちた時に直す先が違う** ため
    // (天井の下回りは「開いたので下げる」、走査の下限は「説明の書き方が変わった」)
    expect(file数, "見本の file を 1 つも見ていない (検査が空振りしている)").toBeGreaterThan(5);
    expect(件.length, "説明の値を 1 件も読めていない (書き方が変わった)").toBe(宣言);
    for (const [名, いま, 上] of [
      ["含む説明", 説明.length, カタカナの天井.説明],
      ["語", 語.length, カタカナの天井.語],
      ["延べ", 延べ, カタカナの天井.延べ],
    ] as const) {
      expect(
        いま,
        `${名} が天井を超えた。 日本語に開くか、同じ図の箱の題が使う語なら天井を上げる (${上} → ${いま})`,
      ).toBeLessThanOrEqual(上);
      expect(いま, `減ったので天井を下げる (${名}: ${上} → ${いま})`).toBeGreaterThanOrEqual(上);
    }
  });

  it("天井が実数ちょうどに置かれている (境界)", () => {
    // 天井を実数より大きく置くと、増えても落ちない。 **ちょうどに置く** ことを固定する
    const { 件 } = 図の説明();
    const { 説明, 語, 延べ } = カタカナを数える(件);
    expect(カタカナの天井.説明, "天井が実数とずれている").toBe(説明.length);
    expect(カタカナの天井.語, "天井が実数とずれている").toBe(語.length);
    expect(カタカナの天井.延べ, "天井が実数とずれている").toBe(延べ);
  });

  it("カタカナを含む説明を混ぜると数が動く (植え込み対照 + 対象外の対照)", () => {
    const 素 = カタカナを数える([]);
    expect([素.説明.length, 素.語.length, 素.延べ], "空の母集団で数が出ている").toEqual([0, 0, 0]);
    // 植え込み対照 = カタカナを含む説明を 1 件混ぜると 3 つとも動く
    const 植えた = カタカナを数える([{ 鍵: "a", 文: "ズヴァイクで束ねる図" }]);
    expect([植えた.説明.length, 植えた.語.length, 植えた.延べ]).toEqual([1, 1, 1]);
    // **既出の語を足す形も延べが拾う** = 含む説明と語の種類は動かないので、
    // この 2 つだけでは *既にカタカナを含む説明に既出の語を足す* 形が素通りする
    const 既出 = カタカナを数える([{ 鍵: "a", 文: "ズヴァイクとズヴァイクを束ねる図" }]);
    expect(
      [既出.説明.length, 既出.語.length, 既出.延べ],
      "同じ説明に同じ語を 2 度書いても延べが 1 しか増えない",
    ).toEqual([1, 1, 2]);
    // 対象外の対照 = 英字だけの説明と、カタカナを持たない日本語では動かない
    const 対象外 = カタカナを数える([
      { 鍵: "b", 文: "signal を図へ繋ぐ" },
      { 鍵: "c", 文: "読む人が値を入れる口の見本" },
    ]);
    expect([対象外.説明.length, 対象外.語.length, 対象外.延べ]).toEqual([0, 0, 0]);
  });
});
