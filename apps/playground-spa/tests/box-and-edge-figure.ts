/**
 * エディタで **箱と矢印が在る図** を開く共通部 (#1477)。
 *
 * ## なぜ既定の見本に依らないか
 *
 * エディタの既定の見本は順序図で、[#1466](https://github.com/cardene777/dragon/issues/1466) から
 * **1 枚の板** として描かれる。 板は名前と呼び名だけを持つので、箱 (`node-body`) も
 * 名札 (`node-label`) も矢印 (`data-cdl-edge`) も 1 つも出ない。
 *
 * その結果、エディタを開いて箱や線を測る検査が 11 file で「1 つも測れていない」 と落ちていた。
 * 板は記法が意図して選んだ形なので、検査の都合で既定の見本を差し替えることはしない。
 * 代わりに **測りたいものが在る図を名指しする**。
 *
 * ## 記法の作り
 *
 * 3 つを固定している。
 *
 * | 書いたこと | 何のためか |
 * |---|---|
 * | `reveal: all` | 矢印を最初から全部出す。 既定 (`phase`) だと出る本数が観測の瞬間で変わる |
 * | `animation` を 2 段 | 光る箱と光らない箱を両方作る。 光り方で色を変える図では、光っていない側が既定の色 |
 * | 矢印に説明文 | 矢印の座布団 (`edge-label-bg`) を出す。 これも色を測る対象 |
 *
 * 実測で 4 秒のあいだ、光っていない箱 2 / 名札 4 / 線 3 / 光っていない矢印 3 / 座布団 3 が
 * 一定だった。 段が進んでも数が動かないので、観測の瞬間に依らない。
 */
import type { Page } from "@playwright/test";

/** 箱と矢印が在る図の記法。 */
export const 箱と矢印の記法 = `title: "箱と矢印の見本"
type: flow
reveal: all

actors:
  - A
  - B
  - C
  - D

flow:
  - A -> B: "呼ぶ"
  - B -> C: "書く"
  - C -> D: "返す"

animation:
  - step: "1 呼ぶ" 1.2s
    focus: [A, B]
  - step: "2 書く" 1.2s
    focus: [B, C]
`;

/**
 * 矢印が **起点から伸びる** 図の記法。
 *
 * 上の記法とは段の作りが違う。 あちらは箱だけを光らせるので矢印は 1 度も伸びない
 * (光っていない矢印が要る検査のため)。 こちらは 1 段目で矢印を名指しするので、
 * 1 段目に伸びて 2 段目以降はそのまま残る。
 *
 * **段を 2 つ置く**。 1 段だけだと段が変わらず、周回のたびに伸び直して落ち着かない。
 *
 * **1 段目を長めに取る** (3 秒)。 画面が組み上がるまでに 1 秒前後かかるので、短いと
 * 見始めた時には伸び終わっている = 伸びる過程を 1 度も観測できない (実測で 1.2 秒だと
 * 最初の観測が既に最終値だった)。
 *
 * **横に並ぶ図にする** (`swimlane`)。 流れ図は箱が縦に積まれるので矢印も縦になり、
 * 終点の x が最初から最後まで動かない = 伸びていても「伸びた」 と読めない (実測)。
 */
export const 矢印が伸びる記法 = `title: "矢印が伸びる見本"
type: swimlane
reveal: all

actors:
  - A
  - B

flow:
  - A -> B: "呼ぶ"

animation:
  - step: "1 呼ぶ" 3.0s
    focus: [A, B, "A -> B"]
  - step: "2 待つ" 1.2s
    focus: [B]
`;

/**
 * 6 つの色味を **1 枚に全部描く** 図の記法 (#1709)。
 *
 * 描画エンジンは矢頭の飾りを **使う分だけ** `<defs>` に出す。 描かれていない色味の矢頭は
 * 画面のどこにも無いので、1 本の矢印を複製して色味だけ差し替える読み方は成立しない
 * (実測 = カタログの画面に出るのは 2 色ぶんだけ)。 6 本すべてを実際に描いて本物を読む。
 *
 * 段は箱だけを名指しする。 矢印を名指しすると光ってしまい、光っていない線の
 * 不透明度を測れなくなる。
 */
export const 六色の記法 = `title: "6 つの色味の見本"
type: flow
reveal: all

actors:
  - A
  - B
  - C
  - D
  - E
  - F
  - G

flow:
  - A -> B: "accent" (accent)
  - B -> C: "teal" (teal)
  - C -> D: "success" (success)
  - D -> E: "error" (error)
  - E -> F: "warning" (warning)
  - F -> G: "info" (info)

animation:
  - step: "1 進む" 1.2s
    focus: [A, B]
  - step: "2 戻る" 1.2s
    focus: [F, G]
`;

/** 記法を URL に載せてエディタへ渡す (`CdlEditor.tsx` の `#s=<base64>`)。 */
export const 記法をURLに載せる = (src: string): string => Buffer.from(src, "utf8").toString("base64");

/**
 * エディタで箱と矢印が在る図を開く。
 *
 * 待ち時間を引数で受けるのは、呼び出し側が測るものによって落ち着くまでの長さが違うため
 * (色を測る側は文字の読込を待つ必要がある)。
 */
export async function 箱と矢印を開く(page: Page, 待ちms = 1500): Promise<void> {
  await page.goto(`editor#s=${記法をURLに載せる(箱と矢印の記法)}`);
  await page.waitForLoadState("networkidle");
  await page.waitForTimeout(待ちms);
}
