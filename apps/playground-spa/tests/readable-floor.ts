/**
 * 見本ごとの「画面上の文字の下限」 の期待値 (#1102)。 検査から参照する共有の期待値で、
 * 検査 file ではない (Playwright は `*.spec.ts` だけを拾う)。
 *
 * ## 実装の定数を import しない
 *
 * `src/lib/readable-scale.ts` の `READABLE_MIN_PX` / `READABLE_RELAXED_PX` を import すると、
 * 実装側の値を変えた時に検査の期待値も一緒に動いて何も落ちなくなる。 ここには実測した数を
 * 書き写す。
 *
 * ## どの見本がどちらに落ちるか
 *
 * 好ましい下限 10px で箱が枠から出る図だけが 8px まで譲る。 窓 1440×900 (絵の枠 840px) での
 * 実測が下の表。
 *
 * | 見本 | 下限 | 理由 |
 * |---|---|---|
 * | `swimlane` | 8px | 10px では箱が枠から出る |
 * | `state-machine` | 8px | 同上 |
 * | `er` | 8px | 同上 |
 * | `class` | 8px | 同上 (#1320 で追加) |
 * | それ以外 | 10px | 箱が枠に収まる |
 *
 * `sequence` は図の外枠が 886px で枠 840px を超えるが、 箱は 17 個すべて内側なので譲らない。
 * 外枠で判定すると全図が譲る側に落ちる (実測)。
 *
 * ## `class` を足した経緯 (#1320)
 *
 * 窓 1440×900 での実測 (2026-08-22)。 `10px にする倍率` は、いまの最小文字を 10px に
 * するために図全体を何倍にするかで、その時の箱の幅を枠 840px と比べる。
 *
 * | 見本 | 最小文字 | 箱幅 | 10px にする倍率 | 10px 時の箱幅 | 枠から出るか |
 * |---|---|---|---|---|---|
 * | `class` | 8.4px | 717px | 1.19 | 853px | 出る (13px) |
 * | `er` | 8.0px | 761px | 1.25 | 951px | 出る |
 * | `swimlane` | 8.0px | 730px | 1.25 | 913px | 出る |
 * | `sequence` | 10.0px | 745px | 1.00 | 745px | 出ない |
 *
 * **見本の中身は変わっていない**。 `editor-samples.ts` の `class` を最後に触ったのは
 * #415 で、それ以降は形も文字も同じ。 描画側 (`@cardenelabs/cdl`) の字の測り方が版を経て
 * 変わり、同じ中身でも箱が広くなったため 10px では収まらなくなった。
 *
 * 譲る側に落とすのは、この file が **実測の記録** で、判定の条件
 * (「10px では箱が枠から出る」) を `class` が満たすため。 描画側を細くする話は別で扱う。
 */

/** 画面上でこれを下回ると本文として読めない (`src/lib/readable-scale.ts` と同じ値を書き写す)。 */
export const MIN_PX = 10;

/** 箱が枠から出る図に限って譲る下限 (同上)。 */
export const RELAXED_PX = 8;

/** 8px まで譲る見本。 窓 1440×900 での実測。 */
export const 譲る見本: readonly string[] = ["swimlane", "state-machine", "er", "class"];

/**
 * 譲っても枠に収まらないので、好ましい下限のまま枠から出る見本 (#2432)。
 *
 * ## 見本は 3 通りに分かれる
 *
 * | 状態 | 画面上の最小文字 | 箱 |
 * |---|---|---|
 * | 枠に収まる | 10px 以上 | 枠の中 |
 * | 譲れば収まる (`譲る見本`) | 8px 台 | 枠の中 |
 * | 譲っても収まらない (この一覧) | 10px のまま | 枠から出る |
 *
 * 3 つ目は `src/lib/readable-scale.ts` の「譲っても収まらないなら譲らない」 が作る状態。
 * 文字を小さくしても見えない箱は見えないままなので、小さくする意味が無い。
 *
 * ## `flow` が 3 つ目に入った経緯 (#2432)
 *
 * #2424 でフローの既定の向きを縦から横にした。 4 人のフローは 4 縦列に広がり、
 * 図が横に長くなる。 窓 1440×900 (絵の枠 840px) での実測 (2026-09-21)。
 *
 * 判定は箱の幅ではなく **箱の右端が枠のどこに来るか** で行う
 * (`readable-scale.ts` の `収まる`)。 図の左に余白があるぶん、右端は箱の幅より右にある。
 *
 * | 見本 | 世界座標の最小文字 | 10px の倍率 | 10px で収まる | 8px の倍率 | 8px で収まる |
 * |---|---|---|---|---|---|
 * | `flow` | 22 | 0.455 | 出る | 0.364 | **出る** |
 * | `swimlane` | 20 | 0.501 | 出る | 0.401 | 収まる |
 * | `er` | 19 | 0.526 | 出る | 0.421 | 収まる |
 * | `class` | 22 | 0.455 | 出る | 0.364 | 収まる |
 * | `topology` | 17.1 | 0.586 | 収まる | — | — |
 * | `pie` | 12 | 0.834 | 収まる | — | — |
 *
 * `flow` だけが 8px まで下げても枠の外に残る。 だから `譲る見本` には入らない
 * (入れると文字が小さくなるだけで、見えない箱は見えないまま)。
 *
 * **箱の幅で判定すると取り違える**。 `flow` の箱の幅は 8px の倍率で 839px になり、
 * 枠 840px に収まるように見える。 実際は図の左に 35 の余白があるぶん右端が外に残る。
 */
export const 譲っても収まらない見本: readonly string[] = ["flow"];

/** 見本の下限 (px)。 窓 1440×900 が前提で、 枠が狭い場合は別の見本も譲る側に落ちる。 */
export const 下限 = (slug: string): number => (譲る見本.includes(slug) ? RELAXED_PX : MIN_PX);
