/**
 * 評価の返答を採点する時の見分け (#3546)。記録の script (`plugin-eval-record.mjs`) が使う。
 *
 * 記録の script は読み込むと評価を回すので、検査から見分けだけを確かめられるよう、ここに分けて置く。
 */

/**
 * 返答が段 `step` を名指すか。
 *
 * 「段 3」「ステップ 3」「Step 3」の形に加え、日本語の「第3段」「3段目」「第3ステップ」も名指しと読む。
 * 評価で、AI が「第3段の段番号が橋の形から浮いてしまう警告が出ました」と崩れを伝えたのに、「段3」の形しか読まずに落とした回があった。
 * 「5段で進む図」のように段の数を言う文は名指しと読まない (「第」も「目」も付かない)
 */
export const namesStep = (reply, step) =>
  new RegExp(
    [
      `(?:段|ステップ|Step|step)\\s*${step}(?!\\d)`,
      `第\\s*${step}\\s*(?:段|ステップ)`,
      `(?<!\\d)${step}\\s*(?:段|ステップ)目`,
    ].join("|"),
    "u",
  ).test(reply);
