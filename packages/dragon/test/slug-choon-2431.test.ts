/**
 * 名前から作る見分けの字で、カタカナの伸ばす音 (`ー`) が残ることの確認 (#2431)。
 *
 * `slugify` は残す字を `ァ-ヶ` (U+30A1-U+30F6) と書いていたため、伸ばす音 (U+30FC) が
 * 範囲の外に落ちて `-` に化けていた。 同じ file のコメントは「英数字と日本語と `-` `_` だけを
 * 残し」 と書いており、伸ばす音は日本語なので、書いた意図と動きが食い違っていた。
 *
 * 困るのは 3 つ。 一覧の 2 行目に `フロ-の並ぶ向きを書かない` と読めない字が出ること、
 * `ユーザー` と `ユーザ` が同じ字に潰れること、画面の検査が探す字を見つけられないこと。
 *
 * **潰れる方を先に見る**。 読めない字は目で気付けるが、潰れる方は図が静かに壊れる
 * (矢印は見分けの字で端を指すため、別の箱へ向かう)。
 */
import { describe, it, expect } from "vitest";
import { slugify, ID_MAX } from "../src/compile/slug";

describe("カタカナの伸ばす音は見分けの字に残る (#2431)", () => {
  it("伸ばす音がそのまま残る", () => {
    expect(slugify("フロー")).toBe("フロー");
    expect(slugify("ユーザー")).toBe("ユーザー");
    expect(slugify("フローの並ぶ向きを書かない")).toBe("フローの並ぶ向きを書かない");
  });

  it("伸ばす音の有無で違う名前が別の字になる", () => {
    // 直す前はどちらも "ユ-ザ" だった = 末尾の `-` も落ちるため完全に一致する
    expect(slugify("ユーザー")).not.toBe(slugify("ユーザ"));
    expect(slugify("サーバー")).not.toBe(slugify("サーバ"));
  });

  it("仮名の端 (ヷヸヹヺ) も残る", () => {
    // `ヶ` (U+30F6) までで切ると `ヷ` (U+30F7) 以降が落ちる。 どれも仮名なので残す
    expect(slugify("ヷヸヹヺ")).toBe("ヷヸヹヺ");
  });

  it("区切りに使う記号は今までどおり - に倒す", () => {
    // 伸ばす音を残すことと、記号を残すことは別。 広げすぎると名前の区切りが消える
    expect(slugify("東京・大阪")).toBe("東京-大阪");
    expect(slugify("こゝろ")).toBe("こ-ろ");
    expect(slugify("ヽヾ")).toBe("n");
  });

  it("ひらがなと漢字と英数字は今までどおり", () => {
    expect(slugify("Foo Bar")).toBe("foo-bar");
    expect(slugify("申し込む")).toBe("申し込む");
    expect(slugify("---")).toBe("n");
  });

  it("切り詰めの上限は伸ばす音を数えても変わらない", () => {
    const 長い = "ー".repeat(ID_MAX + 10);
    expect(slugify(長い)).toHaveLength(ID_MAX);
  });
});
