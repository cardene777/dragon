/*
 * 始まりと終わりの札が、並べ方で出たり出なかったりしないことを見る (#2349)。
 *
 * 状態の図では箱に `initial: true` / `final: true` と書くと「初期」「最終」 の札が付く。
 * 実測 = **縦列を書いた図では札が 1 つも出なかった**。 知らせも出ないので、
 * 縦列を足しただけで別の意味の図になる。
 *
 * 原因は、札を付ける処理が共通の組み立ての 3 つの並べ方のうち **1 つにしか無かった** こと。
 *
 * ## 並べ方を手で並べない
 *
 * 縦列の有無と動きの有無を掛け合わせた 4 通りを回す。 どの組み合わせでも同じ箱に
 * 同じ札が付くことを見る = 並べ方が増えても、札の判定が 1 箇所にある限り揃う。
 */
import { describe, expect, it } from "vitest";
import { compileToCdl } from "../src/compile";
import { parseTextDslV05 } from "../src/v05/parser";

type 書き方 = { 縦列: boolean; 動き: boolean };

/** 縦列と動きの有無を掛け合わせた 4 通り */
const 書き方一覧: 書き方[] = [
  { 縦列: false, 動き: false },
  { 縦列: false, 動き: true },
  { 縦列: true, 動き: false },
  { 縦列: true, 動き: true },
];

const 呼び名 = (w: 書き方): string => `縦列${w.縦列 ? "有" : "無"}・動き${w.動き ? "有" : "無"}`;

/**
 * 状態の図の本文。 `印` は `始まり` / `終わり` / `書かない` のどれかを箱ごとに決める。
 *
 * 縦列を書く形では全ての箱に `lane:` を書く = 一部だけ書いた形は別の経路に落ちる。
 */
function 本文(印: readonly ("始まり" | "終わり" | "書かない")[], w: 書き方): string {
  const 名 = ["受付", "審査", "完了"];
  const 箱 = 名.map((n, i) => {
    const 欄 = [
      "kind: card",
      ...(w.縦列 ? [`lane: c${i === 2 ? 1 : 0}`, `stack: ${i === 2 ? 0 : i}`] : []),
      ...(印[i] === "始まり" ? ["initial: true"] : []),
      ...(印[i] === "終わり" ? ["final: true"] : []),
    ];
    return `  - ${n}: { ${欄.join(", ")} }`;
  });
  return `title: "状態の図"
type: state
${w.縦列 ? "\nlanes:\n  c0: { width: 320 }\n  c1: { width: 320 }\n" : ""}
actors:
${箱.join("\n")}

flow:
  - 受付 -> 審査: "提出"
  - 審査 -> 完了: "承認"
${
  w.動き
    ? `
animation:
  - step: "進む" 1.2s
    focus: ["受付", "審査"]
    description: "受付から審査へ進む"
`
    : ""
}`;
}

/**
 * 箱に付いた始まりと終わりの札。
 *
 * **札の字を 2 つに絞る**。 途中の箱に付く「状態」 の札は、組み立て器を通る経路にしか
 * 出ない = 並べ方で違う値になる別の食い違いで、本 Issue では扱わない (#2352)。
 */
function 始まりと終わりの札(src: string): string {
  const p = parseTextDslV05(src);
  if (!p.ok) throw new Error(`読めない本文: ${p.errors.map((e) => e.message).join(" / ")}`);
  const d = compileToCdl(p.doc, { onNotice: () => {} });
  const 箱 = d.nodes as ReadonlyArray<{ id: string; eyebrow?: string }>;
  return 箱
    .map((n) => `${n.id}:${n.eyebrow === "初期" || n.eyebrow === "最終" ? n.eyebrow : "-"}`)
    .join(" ");
}

/**
 * 書いた値による札の付き方を見る置き方。 どの並べ方でも同じ結果になる。
 *
 * **始まりと終わりを両方書いた形だけを並べる**。 片方しか書かない形は残りの側が
 * 並びで決まる既定に落ちるため、並べ方によって結果が変わる (下の検査が別に見る)。
 */
const 置き方: Record<string, readonly ("始まり" | "終わり" | "書かない")[]> = {
  端に書く: ["始まり", "書かない", "終わり"],
  真ん中に始まりを書く: ["終わり", "始まり", "書かない"],
  終わりを二つ書く: ["始まり", "終わり", "終わり"],
};

/** 1 つも書かない形。 並びで決める既定が効くかは並べ方で変わる */
const 書かない: readonly ("始まり" | "終わり" | "書かない")[] = ["書かない", "書かない", "書かない"];

describe("始まりと終わりの札が、並べ方で出たり出なかったりしない (#2349)", () => {
  it("書き方と置き方を走査できている (空振り防止)", () => {
    expect(書き方一覧.length, "書き方を 1 件も持っていない").toBe(4);
    expect(Object.keys(置き方).length, "置き方を 1 件も持っていない").toBeGreaterThan(0);
  });

  for (const [置き方名, 印] of Object.entries(置き方)) {
    it(`${置き方名} 形で、4 通りの書き方の札が 1 つも違わない`, () => {
      const 結果 = 書き方一覧.map((w) => ({ w, 札: 始まりと終わりの札(本文(印, w)) }));
      const 基準 = 結果[0]!;
      const 違う = 結果
        .filter((r) => r.札 !== 基準.札)
        .map((r) => `${呼び名(r.w)}: ${r.札} (基準 ${呼び名(基準.w)}: ${基準.札})`);
      expect(違う, `走査 ${結果.length} 通り`).toEqual([]);
    });
  }

  it("書いた箱に札が付く (4 通りとも)", () => {
    // 揃っているだけでは足りない。 どこにも札が付かない形でも「1 つも違わない」 は通る
    const 付かない = 書き方一覧
      .map((w) => ({ w, 札: 始まりと終わりの札(本文(置き方.真ん中に始まりを書く!, w)) }))
      .filter(({ 札 }) => !札.includes("審査:初期"))
      .map(({ w, 札 }) => `${呼び名(w)}: ${札}`);
    expect(付かない, `走査 ${書き方一覧.length} 通り`).toEqual([]);
  });

  it("1 つも書かない図は、縦列を書かない形でだけ並びで決まる", () => {
    /*
     * **並びで決める既定は、並びが意味を持つ並べ方でだけ効く** (#2349)。
     *
     * 縦列と段を書いた図は書いた順に左から並ぶわけではないので、「最初に書いた箱」 を
     * 初期とみなす既定は見た目と合わない (実測 = 印の箱で始まりを示している見本に、
     * 「初期」 の字が重ねて出た)。 書いた値はどの並べ方でも効く。
     */
    const 期待 = (w: 書き方): string =>
      w.縦列 ? "受付:- 審査:- 完了:-" : "受付:初期 審査:- 完了:最終";
    const 違う = 書き方一覧
      .map((w) => ({ w, 札: 始まりと終わりの札(本文(書かない, w)) }))
      .filter(({ w, 札 }) => 札 !== 期待(w))
      .map(({ w, 札 }) => `${呼び名(w)}: ${札} (期待 ${期待(w)})`);
    expect(違う, `走査 ${書き方一覧.length} 通り`).toEqual([]);
  });

  it("縦列を書いた図でも、書いた値なら札が付く", () => {
    // 上の検査だけだと「縦列を書いた図では札を出さない」 に倒しても通る
    const 付かない = 書き方一覧
      .filter((w) => w.縦列)
      .map((w) => ({ w, 札: 始まりと終わりの札(本文(置き方.端に書く!, w)) }))
      .filter(({ 札 }) => 札 !== "受付:初期 審査:- 完了:最終")
      .map(({ w, 札 }) => `${呼び名(w)}: ${札}`);
    expect(付かない, `走査 ${書き方一覧.filter((w) => w.縦列).length} 通り`).toEqual([]);
  });

  it("札の見方が違いを見つけられる (植え込み対照)", () => {
    // 端に書いた形と真ん中に書いた形は札の付く箱が違う。 ここが同じに見えるなら、
    // 上の検査は何を比べても通る形に壊れている
    const w = { 縦列: true, 動き: false };
    expect(
      始まりと終わりの札(本文(置き方.端に書く!, w)),
      "置き方を変えても同じ札に見えている",
    ).not.toBe(始まりと終わりの札(本文(置き方.真ん中に始まりを書く!, w)));
  });
});
