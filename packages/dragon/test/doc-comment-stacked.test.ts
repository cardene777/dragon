/**
 * 説明の塊 (`/** ... *\/`) を、空行を挟まずに別の説明の塊の上へ積まないことの検証 (#2066)。
 *
 * 説明とその持ち主の宣言の間に、別の宣言を説明ごと差し込むと、前の説明は持ち主から離れて
 * 直後の別の宣言の上に積み重なる。 持ち主には説明が無くなり、差し込んだ宣言には 2 つの説明が
 * 付く。 公開する型の宣言でも、帯の型 (`DslBand`) に段の説明が重なり、段の型 (`DslPhase`) には
 * 説明が無い状態になっていた。 追跡中の file に 37 か所あった。
 *
 * 差し込みで離れた説明は、必ず「空行を挟まずに続く 2 つの塊」 の形になる。 この形だけを数える。
 * 空行を挟んで離れた説明は拾わない。 空行の有無だけでは、節や file 全体の説明と区別できないため。
 * 節の説明を塊で書く時は、続く説明との間に空行を 1 行置く。
 */
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, it, expect } from "vitest";

const REPO = join(import.meta.dirname, "..", "..", "..");

const 説明の始まり = /^\s*\/\*\*/u;
const 塊の終わり = /\*\//u;

/**
 * 1 file の本文を読み、説明の塊の数と、積み重なった箇所 (後ろの塊が始まる行番号) を返す。
 *
 * 前の塊が説明 (`/**`) で閉じた行の次の行が、別の説明の始まりである箇所を数える。
 * 普通の塊 (`/*`) や `//` の行の後に続く説明は数えない。
 */
function 積み重なった説明(本文: string): { 塊: number; 箇所: number[] } {
  const 行たち = 本文.split("\n");
  let 塊 = 0;
  let 説明の中 = false;
  // まだ 1 つも閉じていない。 -1 にすると先頭行 (i - 1 = -1) の説明を積み重なりと数える
  let 説明が閉じた行: number | null = null;
  const 箇所: number[] = [];
  行たち.forEach((行, i) => {
    if (!説明の中 && 説明の始まり.test(行)) {
      塊++;
      if (説明が閉じた行 !== null && 説明が閉じた行 === i - 1) 箇所.push(i + 1);
      // 同じ行で閉じる塊 (`/** 1 行 *\/`) は、始まりの 3 文字より後ろで閉じを探す
      const 始まりの位置 = 行.indexOf("/**");
      if (塊の終わり.test(行.slice(始まりの位置 + 3))) {
        説明が閉じた行 = i;
      } else {
        説明の中 = true;
      }
      return;
    }
    if (説明の中 && 塊の終わり.test(行)) {
      説明の中 = false;
      説明が閉じた行 = i;
    }
  });
  return { 塊, 箇所 };
}

describe("説明の塊を別の説明の上に積まない (#2066)", () => {
  it("追跡中の *.ts / *.tsx に、空行を挟まずに続く説明の塊が無い", () => {
    const 対象 = execFileSync("git", ["-C", REPO, "ls-files", "*.ts", "*.tsx"], { encoding: "utf8" })
      .split("\n")
      .filter((p) => p !== "");
    expect(対象.length, "file を 1 つも拾えていない (検査が空振りしている)").toBeGreaterThan(0);

    let 数えた塊 = 0;
    const 見つけた: string[] = [];
    for (const rel of 対象) {
      const { 塊, 箇所 } = 積み重なった説明(readFileSync(join(REPO, rel), "utf8"));
      数えた塊 += 塊;
      for (const 行 of 箇所) 見つけた.push(`${rel}:${行}`);
    }
    expect(数えた塊, "説明の塊を 1 つも数えていない (判定が空振りしている)").toBeGreaterThan(0);
    expect(
      見つけた,
      "説明の塊が空行を挟まずに別の説明の上に積まれている (持ち主の宣言の直前へ移す。 節の説明なら空行を 1 行挟む)",
    ).toEqual([]);
  });

  it("空行を挟まずに続く 2 つの説明の塊を拾う", () => {
    // 植え込み対照。 本番の走査は 0 件を期待するので、判定が何にも一致しない形に壊れていても
    // 通ってしまう。 同じ判定に積み重なった形を渡して、拾えることを確かめる
    const 複数行の後 = ["/**", " * 前の宣言の説明", " */", "/** 差し込んだ宣言の説明 */", "function 差し込んだ() {}"];
    expect(積み重なった説明(複数行の後.join("\n")).箇所).toEqual([4]);

    const 一行の後 = ["/** 前の宣言の説明 */", "/**", " * 差し込んだ宣言の説明", " */", "const 差し込んだ = 1;"];
    expect(積み重なった説明(一行の後.join("\n")).箇所).toEqual([2]);
  });

  it("空行を挟んだ塊、普通の塊や行の注記の後の塊、1 行で閉じた塊の後の宣言は拾わない", () => {
    // 陰性対照。 上の対照が、説明の始まりを数えるだけの判定で通っていないことを確かめる
    const 形 = {
      空行を挟む: ["/** 節の説明 */", "", "/** 宣言の説明 */", "const a = 1;"],
      普通の塊の後: ["/* 普通の塊 */", "/** 宣言の説明 */", "const a = 1;"],
      行の注記の後: ["// 行の注記", "/** 宣言の説明 */", "const a = 1;"],
      一行の塊の後の宣言: ["/** 宣言の説明 */", "const a = 1;", "/** 次の宣言の説明 */", "const b = 2;"],
    };
    for (const [名前, 行たち] of Object.entries(形)) {
      expect(積み重なった説明(行たち.join("\n")).箇所, 名前).toEqual([]);
    }
  });
});
