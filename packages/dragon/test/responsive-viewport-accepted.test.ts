/**
 * 読みにくさを受け入れた図の一覧を、**2 つの器で**突き合わせる (#1747 / #1751)。
 *
 * カタログの図のうち、拡大表示 (1150 × 630px) と一覧に並べた枠 (幅 874px、高さの上限なし) で
 * 軸 23 `responsive-viewport` の注意に出るものは **受け入れると決めた** (#1740) =
 * どちらの見せ方でも倍率を上げれば読めるため (#1745 / #1749)。
 *
 * 枚数は書かない = カタログの群を足すたびに動く (実数は `受け入れた一覧` が持つ)。
 *
 * 受け入れたのは **いまの図** であって「境を割る図は何でも受け入れる」 ではない。
 * `responsive-viewport-width-1738.test.ts` は「注意の集合 = 器に収めた倍率が境を割る図の
 * 集合」 を突き合わせるが、**その集合が何枚でも通る** = 新しい 1 枚が出ても落ちない。
 *
 * ここで一覧を名前で持ち、実際に注意が出る図と両方向で突き合わせる。
 *
 * ## 器ごとに回す
 *
 * 検査の中身は器で変わらないので `describe.each` で 2 回回す。 file を分けると、
 * 片方にだけ植え込み対照を足すような形で守りが揃わなくなる。
 *
 * ## 件数でなく名前で持つ
 *
 * 件数を固定すると、境を割らない図を 1 枚足しただけでも書き換えになる。
 * 名前なら **境をまたいだ図が出た時にだけ** 落ちる。
 *
 * ## 両方向で見る
 *
 * 一覧に無い図が注意に出たら落ちる (新しい 1 枚)。 注意に出なくなった図が一覧に残っていても
 * 落ちる (直した図の行が腐らない)。 片側だけだと、対処済の名前が残り続けて一覧が実物から離れる。
 *
 * 一覧そのものと全図の収集は `support/responsive-accepted.ts` が持つ (2 つの器で 12 枚が
 * 重なるため、器ごとに別の file へ書くと片方だけ直って食い違う)。
 */
import { describe, it, expect } from "vitest";
import { visualValidateAll } from "@cardenelabs/cdl";
import type { ValidateOptions } from "@cardenelabs/cdl";

import {
  全図,
  一覧の器,
  受け入れた一覧,
  受け入れた図の名,
  type 器 as 器の種類,
} from "./support/responsive-accepted";

/** カタログに実在する図の id */
const 実在する図 = new Set(全図.map((d) => d.id));

/** 一覧に載っている全ての図 (器を問わない) */
const 全ての受け入れ = 受け入れた一覧.flatMap((g) => g.図);

/** その器で実際に注意が出た図の id (並べ替え済、重複を除く) */
const 注意が出た図の名 = (opts?: ValidateOptions): string[] =>
  [
    ...new Set(
      visualValidateAll(全図, opts).reports.flatMap((r) =>
        r.violations.filter((v) => v.axis === "responsive-viewport").map(() => r.diagramId),
      ),
    ),
  ].sort();

describe("読みにくさを受け入れた図の一覧 (#1747 / #1751)", () => {
  it("カタログの図を 1 枚以上集められている (空振り防止)", () => {
    expect(全図.length, "カタログの図を 1 枚も集められていない (検査が空振りしている)").toBeGreaterThan(
      0,
    );
  });

  it("一覧が空でなく、群の 4 項目が全て埋まっている", () => {
    expect(受け入れた一覧.length, "群が 1 つも無い (検査が空振りしている)").toBeGreaterThan(0);
    for (const g of 受け入れた一覧) {
      expect(g.群.trim(), "群の名前が空").not.toBe("");
      expect(g.理由.trim(), `${g.群} の理由が空`).not.toBe("");
      expect(g.図.length, `${g.群} に図が 1 枚も無い`).toBeGreaterThan(0);
      for (const d of g.図) {
        expect(d.器.length, `${d.id} にどの器で受け入れたかが書かれていない`).toBeGreaterThan(0);
      }
    }
  });

  it("一覧に同じ図が 2 度出てこない", () => {
    const 名 = 全ての受け入れ.map((d) => d.id).sort();
    const 重複 = 名.filter((id, i) => i > 0 && 名[i - 1] === id);
    expect(重複, "一覧に同じ図が 2 度出ている").toEqual([]);
  });

  it("一覧の名前が全てカタログに実在する", () => {
    /*
     * 綴りを間違えると、その名前は永久に注意の集合と一致しない。 下の突き合わせでも落ちるが、
     * 「綴り間違い」 と「図が境をまたいだ」 が同じ文面になるため、先にここで分ける。
     */
    const 実在しない = 全ての受け入れ.map((d) => d.id).filter((id) => !実在する図.has(id));
    expect(実在しない, `一覧にカタログに無い名前がある (図 ${実在する図.size} 枚を走査)`).toEqual([]);
  });
});

/**
 * 器ごとの突き合わせ。
 *
 * 拡大表示は engine の既定なので器を渡さない = 「渡さない時に既定が効く」 ことも同時に固定する。
 */
const 器ごと: [器の種類, ValidateOptions | undefined][] = [
  ["拡大", undefined],
  ["一覧", { container: 一覧の器 }],
];

describe.each(器ごと)("%s の器で受け入れた図と突き合わせる", (器, opts) => {
  const 受け入れた図 = 受け入れた図の名(器);
  const 注意が出た図 = 注意が出た図の名(opts);

  it("その器で受け入れた図が 1 枚以上ある (空振り防止)", () => {
    expect(受け入れた図.length, `${器} の器で受け入れた図が 1 枚も無い`).toBeGreaterThan(0);
  });

  it("注意が 1 件以上出ている (空振り防止)", () => {
    // 0 件だと下の突き合わせが「一覧を空にすれば通る」 形になる
    expect(
      注意が出た図.length,
      `${器} の器で responsive-viewport の注意が 1 件も無い (検査が空振りしている)`,
    ).toBeGreaterThan(0);
  });

  it("一覧に無い図が注意に出ていない", () => {
    const 一覧に無い = 注意が出た図.filter((id) => !受け入れた図.includes(id));
    expect(
      一覧に無い,
      `${器} の器で受け入れていない図が注意に出た。 一覧へ理由付きで足すか、図を直すかを決める`,
    ).toEqual([]);
  });

  it("注意に出ない図が一覧に残っていない", () => {
    const 出ていない = 受け入れた図.filter((id) => !注意が出た図.includes(id));
    expect(
      出ていない,
      `${器} の器で境の内側に入った図が一覧に残っている。 その図の 器 から "${器}" を外す`,
    ).toEqual([]);
  });

  it("突き合わせが両方向とも差を見つけられる (植え込み対照)", () => {
    /*
     * 上の 2 件はどちらも 0 件を期待する。 探し方が何も見つけない形だと永久に通るため、
     * 本番と同じ探し方に **一方だけ欠けた入力** を通して 1 件見つかることを確かめる。
     */
    const 片方欠け = 受け入れた図.slice(1);
    const 一覧に無い = 注意が出た図.filter((id) => !片方欠け.includes(id));
    expect(一覧に無い, "一覧から 1 件外しても差が出ない (突き合わせが効いていない)").toEqual([
      受け入れた図[0]!,
    ]);

    const 余分に持つ = [...受け入れた図, "実在しない図-植え込み"];
    const 出ていない = 余分に持つ.filter((id) => !注意が出た図.includes(id));
    expect(出ていない, "一覧に余分な名前を足しても差が出ない (突き合わせが効いていない)").toEqual([
      "実在しない図-植え込み",
    ]);
  });
});
