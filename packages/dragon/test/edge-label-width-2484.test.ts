/**
 * 図の幅を決めているものが矢印の札であることを、作り物の図で確かめる (#2484)。
 *
 * ## なぜこの検査が要るか
 *
 * `responsive-viewport-accepted.test.ts` は、器に入らない図が新しく出た時に
 * 落ちた言い方へ「最も長い札」 と「札を詰めた時の幅」 を載せる。
 *
 * 載せる値を求める式が壊れていても、**落ちる側が無いと黙って嘘の値が出る**。
 * 式そのものをここで見る。
 *
 * ## 作り物の図で見る
 *
 * 実物の見本で見ると、見本を直した日に一緒に落ちる。 ここで見たいのは
 * 「札を伸ばすと幅が増える」 という関係だけなので、その関係だけを持つ図を作る。
 *
 * 実物の見本が式の対象になっていることは、別の 1 件で空振りを見る。
 */
import { describe, it, expect } from "vitest";
import { diagram, layout } from "@cardenelabs/cdl";
import type { CdlDiagram } from "@cardenelabs/cdl";

import { 幅を決めている札, 幅の理由, 幅の理由をまとめる } from "./support/edge-label-width";
import { 全図 } from "./support/responsive-accepted";

/**
 * 横に並べた 4 列を 3 本の矢印で繋いだ作り物の図。
 *
 * 札を引数で受け取る = 同じ骨格で札だけを変えて幅を比べる。
 */
function 作り物(札: string[]): CdlDiagram {
  const b = diagram("作り物-2484", { topic: "札の長さと幅の関係を見るための図", type: "flow" });
  const 列 = ["列1", "列2", "列3", "列4"];
  for (const l of 列) b.lane(l, { width: 400 });
  列.forEach((l, i) => {
    b.node(`箱${i}`, { lane: l, stack: 0, kind: "service", title: `箱${i}` });
  });
  札.forEach((s, i) => {
    b.edge(`箱${i}`, `箱${i + 1}`, { id: `辺${i}`, label: s });
  });
  return b.build();
}

/** 図の viewBox の幅 */
function 幅(d: CdlDiagram): number {
  return (layout(d) as unknown as { viewBox: { w: number } }).viewBox.w;
}

describe("札の長さが図の幅を決める (#2484)", () => {
  it("札を伸ばすと幅が増える (植え込み対照)", () => {
    const 短い = 幅(作り物(["ああ", "ああ", "ああ"]));
    const 長い = 幅(作り物(["ああああああああ", "ああああああああ", "ああああああああ"]));

    // 空振り防止。 どちらも 0 なら下の比較は何も言っていない
    expect(短い, "作り物の図の幅が 0 (組み立てが壊れている)").toBeGreaterThan(0);
    expect(長い, `短い札で ${短い}、長い札でも幅が増えない`).toBeGreaterThan(短い);
  });

  it("1 本だけ長くても全部の対が広がる", () => {
    /*
     * 描画側は各対の下限を確保したうえで、全対の中心間距離を最も広い対に揃える。
     * そのため 1 本だけ伸ばしても、3 本とも伸ばした時と同じ幅になる。
     * この関係が崩れると「最も長い札」 を載せる意味が消える。
     */
    const 一本だけ = 幅(作り物(["ああ", "ああ", "ああああああああ"]));
    const 全部長い = 幅(作り物(["ああああああああ", "ああああああああ", "ああああああああ"]));
    expect(一本だけ, "1 本だけ伸ばした時と全部伸ばした時で幅が違う").toBe(全部長い);
  });

  it("最も長い札と、詰めた時の幅を返す", () => {
    const d = 作り物(["ああ", "ああああ", "ああああああああ"]);
    const m = 幅を決めている札(d);
    expect(m, "作り物の図で見立てを返さない").not.toBeNull();
    expect(m!.最長の札, "最も長い札を取り違えている").toBe("ああああああああ");
    expect(m!.札の本数, "札の本数が合わない").toBe(3);
    expect(m!.いまの幅, "いまの幅が 0").toBeGreaterThan(0);
    expect(m!.詰めた幅, `詰めても幅が減らない (いま ${m!.いまの幅})`).toBeLessThan(m!.いまの幅);
  });

  it("元の図を書き換えない", () => {
    // 検査は同じ図を何度も読む。 詰めた札が残ると、後の検査が別の図を見ることになる
    const d = 作り物(["ああ", "ああああ", "ああああああああ"]);
    const 前 = JSON.stringify(d);
    幅を決めている札(d);
    expect(JSON.stringify(d), "見立てを取ると元の図が変わる").toBe(前);
  });

  it("矢印の札を持たない図では札を原因にしない", () => {
    const d = 作り物(["", "", ""]);
    expect(幅を決めている札(d), "札が無いのに見立てを返している").toBeNull();
    expect(幅の理由(d), "札が無い図で札を原因として書いている").toContain("矢印の札を持たない");
  });

  it("落ちない時は図を 1 枚も引かない", () => {
    /*
     * 通る時に毎回組み直すと検査が遅くなる。 引く関数が呼ばれた回数で見る
     * (引かなければ組み直しも起きない)。
     */
    let 引いた = 0;
    const 引く = (_id: string): CdlDiagram | undefined => {
      引いた += 1;
      return 作り物(["ああ", "ああああ", "ああああああああ"]);
    };

    expect(幅の理由をまとめる([], 引く), "空の一覧で行を返している").toBe("");
    expect(引いた, "空の一覧なのに図を引いている").toBe(0);

    // 空振り防止。 名前があれば引きに行くことを同じ引く関数で確かめる
    const 行 = 幅の理由をまとめる(["作り物-2484"], 引く);
    expect(引いた, "名前があるのに図を引いていない").toBe(1);
    expect(行, "名前があるのに行が空").toContain("最も長い札");
  });

  it("引いても見つからない名前では行を返さない", () => {
    // 綴り間違いで 1 枚も引けない時に、改行だけの行を足さない
    expect(幅の理由をまとめる(["無い図"], () => undefined), "引けないのに行を返している").toBe("");
  });

  it("実物の見本にも札を持つ図がある (検査の空振り検知)", () => {
    /*
     * 式が正しくても、実物の見本が 1 枚も札を持たなければ落ちた時に何も出ない。
     * 母数を併記する = 0 件が「該当なし」 か「測っていない」 かを分ける。
     */
    const 札を持つ = 全図.filter((d) => 幅を決めている札(d) !== null);
    expect(
      札を持つ.length,
      `見本 ${全図.length} 枚のうち矢印の札を持つ図が 1 枚も無い (式が実物に当たっていない)`,
    ).toBeGreaterThan(0);
  });
});
