/**
 * 書いた省略の印を切れた名前として数えない (#2677)。
 *
 * 末尾が `…` かどうかだけで数えると、engine が幅に入らず切った名前と、描く側が省略の記法
 * として書いた `0x…` が同じ 1 つの数に混ざる。 見本帳の 486 枚で「切れた名前 20 件」 と
 * 出ていたものは全部が後者で、engine が切った名前は 0 件だった。
 *
 * engine は書いてある方に `data-cdl-ellipsis="written"` を付ける (cdl#917)。
 */
import { describe, expect, it } from "vitest";

// @ts-expect-error -- 検査対象は .mjs で型宣言を持たない
import { 切れた名前か, 文字を数える, 書いてある印 } from "../scripts/drawing-measure-run.mjs";

/** 画面から拾う 1 文字の形。 印を持たない文字は `null` で来る */
const 文字 = (文字列: string, 省略の印: string | null = null) => ({ 文字: 文字列, 省略の印 });

describe("切れた名前かを印で分ける (#2677)", () => {
  it("末尾が `…` で印を持たない文字は切れている", () => {
    expect(切れた名前か(文字("新プロジェ…"))).toBe(true);
  });

  it("末尾が `…` でも書いてある印を持つ文字は切れていない", () => {
    expect(切れた名前か(文字("0x…", 書いてある印))).toBe(false);
  });

  it("末尾が `…` でない文字は印の有無によらず切れていない", () => {
    expect(切れた名前か(文字("すぐ取る"))).toBe(false);
    expect(切れた名前か(文字("すぐ取る", 書いてある印))).toBe(false);
  });

  it("途中に `…` を含む名前は切れていない (陰性対照)", () => {
    // `pie / bar / …` のような書き方を切れた名前として数えない
    expect(切れた名前か(文字("pie / … / bar"))).toBe(false);
  });

  it("知らない値の印は書いてある印として扱わない", () => {
    // 印は 1 つの値だけを書いてあるものとみなす。 別の値を「印がある」 と読むと、
    // engine が後から別の用途で同じ属性を使った時に切れた名前が消える
    expect(切れた名前か(文字("名前…", "cut"))).toBe(true);
    expect(切れた名前か(文字("名前…", ""))).toBe(true);
  });
});

describe("拾った文字から 3 つの数を出す (#2677)", () => {
  it("印を持つ省略を切れた名前に数えない", () => {
    const r = 文字を数える([
      文字("0x…", 書いてある印),
      文字("0x…", 書いてある印),
      文字("#420"),
    ]);
    expect(r.切れた名前).toBe(0);
    expect(r.文字の件数).toBe(3);
  });

  it("印を持たない省略は数える", () => {
    const r = 文字を数える([文字("新プロジェ…"), 文字("0x…", 書いてある印)]);
    expect(r.切れた名前).toBe(1);
  });

  it("読める字は省略の印と空白を除いた数", () => {
    // 折り返しの改行を 1 字と数えると、同じ名前が枠の幅で増減する
    const r = 文字を数える([文字("すぐ 取る\n今週"), 文字("0x…", 書いてある印)]);
    expect(r.読める字).toBe(6 + 2);
  });

  it("文字の件数は印によらず全部を数える", () => {
    // 件数は「描かれた文字がいくつあるか」 で、切れているかとは別の数
    const r = 文字を数える([文字("0x…", 書いてある印), 文字("あ"), 文字("い…")]);
    expect(r.文字の件数).toBe(3);
    expect(r.切れた名前).toBe(1);
  });

  it("文字が 0 件なら 3 つとも 0 になる", () => {
    expect(文字を数える([])).toEqual({ 文字の件数: 0, 切れた名前: 0, 読める字: 0 });
  });
});

describe("印を出さない engine で測った時 (#2677)", () => {
  it("書いてある省略も切れた名前として数える = 見落とす側へ倒れない", () => {
    // 印を持たない版の engine で測ると、書いてある `0x…` も数えられる。
    // 過剰に報告する側なので、調べれば印が無いことが分かる。
    // 逆向き (engine が切った側に印を付ける) だと、印の無い版で 0 件と出て
    // 実際に切れている名前が永久に数えられない
    const r = 文字を数える([文字("0x…"), 文字("0x…")]);
    expect(r.切れた名前).toBe(2);
  });
});
