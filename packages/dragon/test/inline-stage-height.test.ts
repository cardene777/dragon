/**
 * 一覧の台に描かれる高さを数える (#1753)。
 *
 * `#1751` は一覧の枠 (幅 874px) で **文字が小さくなる側** を測った。 同じ枠には逆向きの
 * 性質がある = 台は幅に合わせて図を伸ばすので、細い図ほど大きく伸びて縦に長くなる。
 * そちらは 1 度も測っていなかった。
 *
 * ## 線は基準の画面の高さに引く
 *
 * `縦に長い線` は 900px = この repo が画面の実測に使ってきた画面の高さ。 ここより長い図は
 * どの位置まで巻き上げても 1 画面に入り切らない。
 *
 * 「巻き上げずに見える高さ」 (実測 338px) には引かない = その線ではほぼ全枚数が引っかかる。
 * 一覧は元々巻き上げて見る面で、1 画面に収まることを求めていない。
 *
 * ## 伸ばすのをやめる道は採らなかった
 *
 * 台に伸びの上限を入れるか高さの頭打ちを入れれば長さは消えるが、444 枚中 238 枚の見え方が
 * 変わる。 幅に合わせて伸ばすのは `CdlDiagramView` の長年の挙動で、読み手には倍率の操作が
 * ある (#1749)。 見え方を変えずに済む道があるうちは 238 枚を動かさない。
 *
 * ## 名前で持って両方向で見る
 *
 * `#1747` / `#1751` と同じ形。 一覧に無い図が線を超えたら落ち、線の内側に入った図が
 * 一覧に残っていても落ちる。
 */
import { describe, it, expect } from "vitest";
import { layout } from "@cardenelabs/cdl";

import {
  全図,
  一覧の器,
  一覧で描かれる高さ,
  縦に長い線,
  縦に長い一覧,
  縦に長い図の名,
} from "./support/responsive-accepted";

/** 見本帳に実在する図の id */
const 実在する図 = new Set(全図.map((d) => d.id));

/** 一覧の台に描かれる高さ (図の id をつけて全枚数分) */
const 描かれる高さ = 全図.map((d) => ({ id: d.id, 高さ: 一覧で描かれる高さ(layout(d).viewBox) }));

/** 線を超えた図の id (並べ替え済) */
const 線を超えた図 = [...new Set(描かれる高さ.filter((r) => r.高さ > 縦に長い線).map((r) => r.id))].sort();

/** 手で書いた一覧 */
const 受け入れた図 = 縦に長い図の名();

describe("一覧の台に描かれる高さ (#1753)", () => {
  it("見本帳の図を 1 枚以上集められている (空振り防止)", () => {
    expect(全図.length, "見本帳の図を 1 枚も集められていない (検査が空振りしている)").toBeGreaterThan(
      0,
    );
    expect(
      描かれる高さ.length,
      "高さを 1 枚も測れていない (検査が空振りしている)",
    ).toBe(全図.length);
  });

  it("高さの導き方が画面の実測と一致する", () => {
    /*
     * 式が実物から離れると、この file の全ての判定が別のものを測る。
     * 画面 1440 × 900 の実測で `parts-traffic-light-stack` は 874 × 2292px に描かれた。
     */
    const 実測の図 = 描かれる高さ.find((r) => r.id === "parts-traffic-light-stack");
    expect(実測の図, "実測に使った図が見本帳から消えている").toBeDefined();
    expect(Math.round(実測の図!.高さ)).toBe(2292);
    expect(一覧の器.width).toBe(874);
    expect(縦に長い線).toBe(900);
  });

  it("一覧が空でなく、群の 3 項目が全て埋まっている", () => {
    expect(縦に長い一覧.length, "群が 1 つも無い (検査が空振りしている)").toBeGreaterThan(0);
    for (const g of 縦に長い一覧) {
      expect(g.群.trim(), "群の名前が空").not.toBe("");
      expect(g.理由.trim(), `${g.群} の理由が空`).not.toBe("");
      expect(g.図.length, `${g.群} に図が 1 枚も無い`).toBeGreaterThan(0);
    }
  });

  it("一覧に同じ図が 2 度出てこない", () => {
    const 重複 = 受け入れた図.filter((id, i) => i > 0 && 受け入れた図[i - 1] === id);
    expect(重複, "一覧に同じ図が 2 度出ている").toEqual([]);
  });

  it("一覧の名前が全て見本帳に実在する", () => {
    // 綴り間違いと「図が線をまたいだ」 を同じ文面にしないため、先にここで分ける
    const 実在しない = 受け入れた図.filter((id) => !実在する図.has(id));
    expect(実在しない, `一覧に見本帳に無い名前がある (図 ${実在する図.size} 枚を走査)`).toEqual([]);
  });

  it("線を超える図が 1 枚以上ある (空振り防止)", () => {
    // 0 枚だと下の突き合わせが「一覧を空にすれば通る」 形になる
    expect(
      線を超えた図.length,
      `${縦に長い線}px を超える図が 1 枚も無い (検査が空振りしている)`,
    ).toBeGreaterThan(0);
  });

  it("一覧に無い図が線を超えていない", () => {
    const 一覧に無い = 線を超えた図.filter((id) => !受け入れた図.includes(id));
    expect(
      一覧に無い,
      `受け入れていない図が ${縦に長い線}px を超えた。 一覧へ理由付きで足すか、図を直すかを決める`,
    ).toEqual([]);
  });

  it("線の内側に入った図が一覧に残っていない", () => {
    const 超えていない = 受け入れた図.filter((id) => !線を超えた図.includes(id));
    expect(超えていない, "線の内側に入った図が一覧に残っている。 一覧から外す").toEqual([]);
  });

  it("突き合わせが両方向とも差を見つけられる (植え込み対照)", () => {
    /*
     * 上の 2 件はどちらも 0 件を期待する。 探し方が何も見つけない形だと永久に通るため、
     * 本番と同じ探し方に **一方だけ欠けた入力** を通して 1 件見つかることを確かめる。
     */
    const 片方欠け = 受け入れた図.slice(1);
    const 一覧に無い = 線を超えた図.filter((id) => !片方欠け.includes(id));
    expect(一覧に無い, "一覧から 1 件外しても差が出ない (突き合わせが効いていない)").toEqual([
      受け入れた図[0]!,
    ]);

    const 余分に持つ = [...受け入れた図, "実在しない図-植え込み"];
    const 超えていない = 余分に持つ.filter((id) => !線を超えた図.includes(id));
    expect(超えていない, "一覧に余分な名前を足しても差が出ない (突き合わせが効いていない)").toEqual([
      "実在しない図-植え込み",
    ]);
  });
});
