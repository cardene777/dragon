/*
 * 状態の図の「書かなかった時の既定」 が、経路で変わらないことを見る (#2352)。
 *
 * 状態の図には組み立ての経路が 2 つある。 動きも縦列も書かない図は状態の図の組み立て器を
 * 通り、どちらかを書いた図は段を持つ図の共通の組み立てを通る。 実測 = **2 つで既定が
 * 揃っておらず**、同じ本文でも動きの段を 1 つ足すだけで箱が札の形から人の形に変わり、
 * 途中の箱から「状態」 の札が消えていた。
 *
 * ```
 * 動きも縦列も書かない  受付[card]:初期  審査[card]:状態  完了[card]:最終
 * 動きを書いた         受付[actor]:初期 審査[actor]:-    完了[actor]:最終
 * ```
 *
 * カタログの記法の頁の「認証の状態遷移」 が、種類を書かず動きだけを書いているため
 * 既にこの形で出ていた。
 *
 * ## 経路を手で並べない
 *
 * 縦列の有無と動きの有無を掛け合わせた 4 通りを回す。 どの組み合わせでも箱の形と札が
 * 同じことを見る = 経路が増えても、既定が 1 箇所にある限り揃う。
 */
import { describe, expect, it } from "vitest";
import { compileToCdl } from "../src/compile";
import { 状態の図の既定の種類 } from "../src/compile/state";
import { parseTextDslV05 } from "../src/v05/parser";

type 書き方 = { 縦列: boolean; 動き: boolean };

const 書き方一覧: 書き方[] = [
  { 縦列: false, 動き: false },
  { 縦列: false, 動き: true },
  { 縦列: true, 動き: false },
  { 縦列: true, 動き: true },
];

const 呼び名 = (w: 書き方): string => `縦列${w.縦列 ? "有" : "無"}・動き${w.動き ? "有" : "無"}`;

/** 状態の図の本文。 `種類` を渡すと全ての箱にその種類を書く */
function 本文(w: 書き方, 種類?: string): string {
  const 名 = ["受付", "審査", "完了"];
  const 箱 = 名.map((n, i) => {
    const 欄 = [
      ...(種類 === undefined ? [] : [`kind: ${種類}`]),
      ...(w.縦列 ? [`lane: c${i === 2 ? 1 : 0}`, `stack: ${i === 2 ? 0 : i}`] : []),
    ];
    return 欄.length === 0 ? `  - ${n}` : `  - ${n}: { ${欄.join(", ")} }`;
  });
  return `title: "状態の図"
type: state
${w.縦列 ? "\nlanes:\n  c0: { width: 320 }\n  c1: { width: 320 }\n" : ""}
actors:
${箱.join("\n")}

flow:
  - 受付 -> 審査: "提出"
  - 審査 -> 完了: "承認"
${
  w.動き
    ? `
animation:
  - step: "進む" 1.2s
    focus: ["受付", "審査"]
    description: "受付から審査へ進む"
`
    : ""
}`;
}

/** 箱の形だけを 1 本の字にする。 札は並べ方で決まる既定を含むので別に見る */
function 箱の形だけ(src: string): string {
  return 形と札(src).replace(/:[^\s]*/gu, "");
}

/** 箱の形と札を 1 本の字にする */
function 形と札(src: string): string {
  const p = parseTextDslV05(src);
  if (!p.ok) throw new Error(`読めない本文: ${p.errors.map((e) => e.message).join(" / ")}`);
  const d = compileToCdl(p.doc, { onNotice: () => {} });
  const 箱 = d.nodes as ReadonlyArray<{ id: string; kind?: string; eyebrow?: string }>;
  return 箱.map((n) => `${n.id}[${n.kind ?? "-"}]:${n.eyebrow ?? "-"}`).join(" ");
}

describe("状態の図の書かなかった時の既定が、経路で変わらない (#2352)", () => {
  it("書き方を走査できている (空振り防止)", () => {
    expect(書き方一覧.length, "書き方を 1 件も持っていない").toBe(4);
  });

  it("種類を書かない図の箱の形が、4 通りとも同じ", () => {
    const 結果 = 書き方一覧.map((w) => ({ w, 形: 箱の形だけ(本文(w)) }));
    const 基準 = 結果[0]!;
    const 違う = 結果
      .filter((r) => r.形 !== 基準.形)
      .map((r) => `${呼び名(r.w)}: ${r.形} (基準 ${呼び名(基準.w)}: ${基準.形})`);
    expect(違う, `走査 ${結果.length} 通り`).toEqual([]);
  });

  it("札は縦列の有無で決まる既定に従う", () => {
    /*
     * **並びで決める既定は、並びが意味を持つ並べ方でだけ効く** (#2349)。
     *
     * 縦列と段を書いた図は書いた順に左から並ぶわけではないので、「最初に書いた箱」 を
     * 初期とみなす既定は見た目と合わない。 途中の箱の札 (「状態」) は並びに依らないので
     * どの並べ方でも付く。
     */
    const 期待 = (w: 書き方): string =>
      w.縦列
        ? "受付[card]:状態 審査[card]:状態 完了[card]:状態"
        : "受付[card]:初期 審査[card]:状態 完了[card]:最終";
    const 違う = 書き方一覧
      .map((w) => ({ w, 形: 形と札(本文(w)) }))
      .filter(({ w, 形 }) => 形 !== 期待(w))
      .map(({ w, 形 }) => `${呼び名(w)}: ${形} (期待 ${期待(w)})`);
    expect(違う, `走査 ${書き方一覧.length} 通り`).toEqual([]);
  });

  it("種類を書かない箱が、状態の図の既定の形になる (4 通りとも)", () => {
    // 揃っているだけでは足りない。 4 通りとも人の形に倒しても「同じ」 は通る
    const 違う = 書き方一覧
      .map((w) => ({ w, 形: 形と札(本文(w)) }))
      .filter(({ 形 }) => !形.includes(`[${状態の図の既定の種類}]`))
      .map(({ w, 形 }) => `${呼び名(w)}: ${形}`);
    expect(違う, `既定の形 = ${状態の図の既定の種類}`).toEqual([]);
  });

  it("途中の箱に状態の札が付く (4 通りとも)", () => {
    const 付かない = 書き方一覧
      .map((w) => ({ w, 形: 形と札(本文(w)) }))
      .filter(({ 形 }) => !形.includes("審査[card]:状態"))
      .map(({ w, 形 }) => `${呼び名(w)}: ${形}`);
    expect(付かない, `走査 ${書き方一覧.length} 通り`).toEqual([]);
  });

  it("印の形を書いた箱には札が付かない (4 通りとも)", () => {
    /*
     * 印の箱 (`mark-start` / `mark-end`) は形そのものが始点と終点を表す。
     * 字を重ねると同じことを 2 度言う = 実測で、既定を無条件に配った時に
     * 印の箱へ「初期」 の字が出て見本が壊れた (#2349 の突き合わせが 2 件落ちた)。
     */
    const 付いた = 書き方一覧
      .map((w) => ({ w, 形: 形と札(本文(w, "mark-start")) }))
      .filter(({ 形 }) => !/^\S+\[mark-start\]:-( \S+\[mark-start\]:-)*$/u.test(形))
      .map(({ w, 形 }) => `${呼び名(w)}: ${形}`);
    expect(付いた, `走査 ${書き方一覧.length} 通り`).toEqual([]);
  });

  it("書いた種類はそのまま通る (4 通りとも)", () => {
    // 既定を引く処理が、書いた種類を上書きしていないこと
    const 上書き = 書き方一覧
      .map((w) => ({ w, 形: 形と札(本文(w, "storage")) }))
      .filter(({ 形 }) => !形.includes("[storage]"))
      .map(({ w, 形 }) => `${呼び名(w)}: ${形}`);
    expect(上書き, `走査 ${書き方一覧.length} 通り`).toEqual([]);
  });

  it("形と札の見方が違いを見つけられる (植え込み対照)", () => {
    // 種類を書いた図と書かない図は形が違う。 ここが同じに見えるなら、
    // 上の検査は何を比べても通る形に壊れている
    const w = { 縦列: false, 動き: true };
    expect(形と札(本文(w)), "種類を書いても書かなくても同じに見えている").not.toBe(
      形と札(本文(w, "storage")),
    );
  });
});
