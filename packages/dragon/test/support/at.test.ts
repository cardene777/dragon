/**
 * 並びから要素を取り出す道具の検査 (#1414)。
 *
 * この道具は 9 file の検査が呼ぶ。 **落ちる時に何が無かったかを残す** のが役目で、
 * それが効いているかは道具そのものでしか見られない。
 *
 * ## なぜ道具の検査が要るか
 *
 * 変異試験で `at` の確認を外して `xs[i] as T` に戻しても、呼ぶ側の 420 件は 1 件も
 * 落ちなかった。 いま通っている検査は要素が実在する場面でしか呼んでおらず、
 * **無かった時の振る舞いを誰も見ていなかった** ため。
 *
 * 分類は `rules/quality.md` 条件 5 の「到達する入力を作れる」 = 呼ぶ側では作れないが、
 * 道具を直接呼べば作れる。 ここで作る。
 */
import { describe, it, expect } from "vitest";

import { at, 引く } from "./at";

describe("並びから要素を取り出す (#1414)", () => {
  it("要素があればそのまま返す", () => {
    expect(at(["a", "b"], 1, "xs")).toBe("b");
  });

  it("無い添字は何が無かったかを残して落ちる", () => {
    /*
     * `!` で潰すと `Cannot read properties of undefined` で落ち、**落ちる場所が原因から
     * 離れる**。 何番目が無かったのかも、並びの長さがいくつだったのかも残らない。
     */
    expect(() => at(["a"], 5, "xs")).toThrow(/xs\[5\] が無い/);
    expect(() => at(["a"], 5, "xs")).toThrow(/長さ 1/);
  });

  it("空の並びでも落ちる", () => {
    expect(() => at([], 0, "xs")).toThrow(/長さ 0/);
  });

  it("`undefined` を値として持つ並びは無いものとして落ちる", () => {
    /*
     * 値が `undefined` の要素と、要素が無いことを区別しない。 どちらも「引けなかった」
     * ので、区別すると呼ぶ側が `undefined` を掴んだまま進む。
     */
    expect(() => at([undefined], 0, "xs")).toThrow(/xs\[0\] が無い/);
  });
});

describe("表から値を引く (#1414)", () => {
  it("鍵があればそのまま返す", () => {
    expect(引く({ a: 1 }, "a", "表")).toBe(1);
  });

  it("無い鍵はある鍵を並べて落ちる", () => {
    expect(() => 引く({ a: 1, b: 2 }, "c", "表")).toThrow(/表 に "c" が無い/);
    expect(() => 引く({ a: 1, b: 2 }, "c", "表")).toThrow(/ある鍵: a, b/);
  });

  it("空の表は「ある鍵: なし」 と出す", () => {
    // 鍵の一覧が空文字だと、表が空なのか出力が壊れたのか読めない
    expect(() => 引く({}, "a", "表")).toThrow(/ある鍵: なし/);
  });
});
