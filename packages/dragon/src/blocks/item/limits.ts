/**
 * 列の図の見た目。図の種類の行の `[shape: <見た目>]` で選び、書かない列の図は箱を縦の帯にしたボードに並べる。
 * `layers` は箱を書いた順に上から横の帯に重ね、札が段ごとに帯を下りて、帯ごとの `note` を印に残す。
 * `stations` は箱を書いた順に 1 本の流れの線の上の駅にし、札を駅の下に積んで、札が線の上を次の駅へ走る。
 * `stairs` は層の見た目の帯を下の層ほど右へずらした階段にし、層の箱に `time` を書くと経った時間の目盛りと針を添える (#3640)
 */
export const LINEUP_SHAPES = ["layers", "stations", "stairs"] as const;

export type LineupShape = (typeof LINEUP_SHAPES)[number];

/** 層の見た目と階段の見た目で重ねる層の上限 (#3625)。9 つ以上の帯は、1 枚の図の高さに収めると帯の字が読めなくなる */
export const LAYERS_MOST = 8;
