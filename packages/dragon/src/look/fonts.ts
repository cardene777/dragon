/** 等幅の字の幅 (1000 分率)。どの字も同じ幅。 */
export const MONO_ADVANCE = 600;

/** 全角として数える字の始まり。仮名と漢字と全角の記号はここから後ろにある。 */
export const WIDE_FROM = 0x2e80;

export type Family = keyof typeof FONTS;

/** 字の大きさを 1000 とした時の幅。上の表はこの単位で持つ。 */
export const EM = 1000;

/** 1 字の幅 (1000 分率)。表に無い字は全角とする。 */
export function advance(ch: string, family: Family): number {
  if ((ch.codePointAt(0) ?? 0) >= WIDE_FROM) return EM;
  if (family === "mono") return MONO_ADVANCE;
  return SANS_ADVANCE[ch] ?? EM;
}
