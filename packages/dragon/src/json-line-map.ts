/**
 * JSON / YAML の本文で「どこに書いたか」 を指す鍵と、そこから行番号を引く表 (#2117)。
 *
 * JSON を読む経路は行番号を持たないため、組み立ての知らせは全て 0 行になり、画面は
 * 「どの行の話か」 を出せなかった。 本文の行が分かる入口 (編集画面の YAML 欄) は、本文を
 * 読む時に場所ごとの行を集めてこの表で渡す。 表を渡さない呼出 (LLM が作った JSON を直に
 * 渡す経路) は今までどおり 0 行になる。
 *
 * 鍵の形は RFC 6901 (JSON Pointer) と同じにする (`/actors/1` / `/values/sales`)。
 * 名前をそのまま `.` で繋ぐ形にすると、`values` に `a.b` という名前を書いた場所と、
 * `values.a` の中の `b` という欄が同じ鍵になる。 `/` と `~` を書き換える規則があるため、
 * この形では重ならない。
 *
 * 表を作る側 (`apps/playground-spa/src/lib/yaml-lines.ts`) と引く側 (`json-parser.ts`) は
 * 同じ関数を呼ぶ。 別々に持つと、片方だけ直した時に **全ての行が引けなくなる** =
 * 引けない状態は知らせが 0 行に戻るだけで、図も誤りも変わらないため気付けない。
 */

/** 本文の場所 (JSON Pointer) から、元の本文の行番号 (1 始まり) を引く表。 */
export type 書いた行の表 = ReadonlyMap<string, number>;

/**
 * 場所を指す鍵を作る。 引数は上から順に、欄の名前と並びの番号。
 *
 * 文書そのものは引数なしで空文字になる。 1 つずつ足す時は、親の鍵に
 * `書いた場所の鍵(次の区切り)` を繋げる (同じ結果になる)。
 */
export function 書いた場所の鍵(...道: readonly (string | number)[]): string {
  return 道.map((区切り) => `/${String(区切り).replace(/~/g, "~0").replace(/\//g, "~1")}`).join("");
}
