import type { DslDocument, PresetType } from "../types";
/**
 * 箱に書いた縦列の扱い (#2030 で `compile.ts` から移した)。
 *
 * 縦列を書ける図種と、書いた縦列をそのまま使うかの判定。
 *
 * **葉に置く** = 図種ごとの file と、`compile.ts` に残る「書いたのに効かない」 の知らせの
 * 両方が呼ぶ。
 */

/**
 * 縦列を選べる図種 (#1263)。
 *
 * 縦列を **箱を並べるための入れ物** として使う図種だけを許す。 順序図と solidity は
 * 縦列がそのまま生命線として描かれる骨格なので許さない (#1248 の判断はこちらに当たる)。
 *
 * `er` は「1 縦列 1 箱」 が図の読み方そのもの (表が横に並ぶ) なので、2 つの箱を同じ縦列へ
 * 入れられる形にはしない。
 *
 * **クラス図と状態遷移図は外した** (#1466)。 設計が格子に置く形になり (クラス 3 列 3 段 /
 * 状態 2 列 5 段)、「箱の 1 つの辺には関係を 1 本まで」 を守るには 1 つの縦列に複数の箱が要る。
 * 「1 縦列 1 箱」 が読み方だった前提はここで崩れている。
 */
export const 縦列を選べる図種: ReadonlySet<PresetType> = new Set<PresetType>([
  "flow",
  "topology",
  "swimlane",
  /*
   * 分かれ道の図 (#2513)。
   *
   * この図種は **縦列が役割で、箱はその中に置く**。 1 人の役割の中に複数の箱が並ぶ形
   * (申請を出す / 直して出し直す) が図の読み方そのものなので、書いた縦列をそのまま使う。
   */
  "flowchart",
  "class",
  "state",
  /*
   * ER 図 (#1571)。
   *
   * `er` の組み立て器は実体 1 つにつき帯を 1 本作り、必ず段 0 に置く = 表が横 1 列にしか
   * 並ばない。 関係を 4 本持つ実体があると、どう並べ替えても 2 本は隣を飛び越す
   * (意匠帳 `docs/design/er/note.md` § 記法の制約 が 4 通りを実測しており、1 列は縦横比 7.0 /
   * 最長の線 4068、格子は 3.5 / 836)。
   *
   * **全ての箱が縦列を書いた時だけ** 効くので、書かない図はいままでどおり組み立て器が並べる。
   */
  "er",
]);

/**
 * 書いた縦列に箱を置く形か (#1263)。
 *
 * **全ての箱が縦列を書いた時だけ** この形にする。 一部だけ書いた形は、書かなかった箱の
 * 行き先を決める規則が要る (既定の縦列に集める / 自分の縦列を作る) が、どちらも
 * 書いた人の意図と一致する保証が無い。 混ざった形は `reportLaneMixed` が知らせる。
 *
 * 数える箱は `縦列の判定に数える箱` が決める (#2372)。
 */
export function 書いた縦列に置く(kind: PresetType, doc: DslDocument): boolean {
  if (!縦列を選べる図種.has(kind)) return false;
  const 対象 = 縦列の判定に数える箱(doc);
  return 対象.length > 0 && 対象.every((a) => a.lane !== undefined);
}

/**
 * 縦列の判定で数える箱 (#2372)。
 *
 * **見本 (`parts`) は縦列を書いた時だけ数える**。 見本の縦列は張替え先の指定で、
 * 箱を並べる話ではない = 書いていない見本を数に入れると、普通の箱が全部書いた図まで
 * 「一部だけ書いた」 に倒れる。
 *
 * 逆に見本を **常に** 外すと、箱が全部見本の図で対象が 0 件になり
 * 「全ての箱が縦列を書いた」 が成立しない。 結果は 3 つ重なる =
 * 書いた縦列に箱が入らない / 宣言した縦列が空のまま残る / 誤って「どの箱も入らない」 と知らせる
 * (実測 = カタログの見本 19 枚で知らせが 38 件)。
 *
 * 見本が混ざった図では普通の箱が対象になって成立し、**見本も一緒に書いた縦列へ入っていた**
 * = 見本を縦列へ入れられないわけではなく、数え方だけが割れていた。
 *
 * **置く側と知らせる側で同じ数え方を使う**。 別々に数えると、見本だけの図で
 * 「一部だけ書いた」 形が知らせずに落ちる。
 */
export function 縦列の判定に数える箱(doc: DslDocument): DslDocument["actors"] {
  const 見本が縦列を書いた = doc.actors.some((a) => a.partId !== undefined && a.lane !== undefined);
  return 見本が縦列を書いた ? doc.actors : doc.actors.filter((a) => a.partId === undefined);
}

/**
 * 縦列ごとに箱の段を決める (#1394 / #2396)。
 *
 * 段は **書いた番号をそのまま持つ**。 書き順で 0 から詰め直すと、`stack: 1` と書いた箱が
 * 0 へ落ちる = 決定木のように「同じ高さに並ばない」 ことが図の意味そのものになる形では、
 * 詰めた瞬間に別の図になる (実測 = 3 段の木の根が 1 段目へ上がった)。
 *
 * 書かなかった箱は、その縦列で **空いている一番小さい段** に置く。 単に数え上げると
 * 書いた番号と重なり、2 つの箱が同じ段に載る。
 *
 * **箱を並べる図種すべてが同じ決め方を使う** (#2396)。 クラス図だけこの決め方を持たず、
 * 段を書かない箱を全て 0 に残していた。 同じ縦列に箱を 2 つ置くと配置の計算が
 * 「同じ場所に 2 つある」 として投げ、図が 1 枚も描けない (実測 = 24 図種で落ちるのは
 * クラス図だけ)。
 *
 * @param actors 記法から読んだ箱を書いた順に並べたもの
 * @returns 段を持つ箱だけの表。 縦列も段も書かない箱は入らない (呼出側が既定に任せる)
 */
export function 縦列ごとの段を決める(
  actors: DslDocument["actors"],
): ReadonlyMap<DslDocument["actors"][number], number> {
  const 埋まった段 = new Map<string, Set<number>>();
  const 埋める = (lid: string, stack: number): void => {
    const 集合 = 埋まった段.get(lid) ?? new Set<number>();
    集合.add(stack);
    埋まった段.set(lid, 集合);
  };
  // 書いた番号を先に全て埋める = 書き順が後の箱の番号とも重ならない
  for (const a of actors) {
    if (a.lane !== undefined && a.stack !== undefined) 埋める(a.lane, a.stack);
  }
  const 決めた = new Map<DslDocument["actors"][number], number>();
  for (const a of actors) {
    if (a.lane === undefined) {
      // 縦列を書かない箱は縦列の中の段を持たない。 段だけ書いた箱はその番号を渡す
      if (a.stack !== undefined) 決めた.set(a, a.stack);
      continue;
    }
    if (a.stack !== undefined) {
      決めた.set(a, a.stack);
      continue;
    }
    let stack = 0;
    const 集合 = 埋まった段.get(a.lane);
    while (集合?.has(stack)) stack += 1;
    埋める(a.lane, stack);
    決めた.set(a, stack);
  }
  return 決めた;
}
