/**
 * 出どころと行き先だけを使う図で、効かないと伝えない矢印の欄 (#2364 / #2366)。
 *
 * 骨格の図 (`tree` / `mind`) は矢印を親子のつながりとして描き、
 * ガントチャート (`gantt`) は矢印を前後の関係として読む。 どちらも向きしか使わないので除外は同じ。
 *
 * | 区分 | 欄 |
 * |---|---|
 * | 矢印が使う | 出どころ / 行き先 と、行番号と書いた場所 |
 * | 別の知らせが受け持つ | 部品の端 (`part-node-ignored`) |
 *
 * 文字 (`label`) は除外しない = どちらの図種も描かないので伝える。
 * 空の時だけ書いていない扱いにするのは `効かない矢印の欄を並べる` が受け持つ。
 *
 * **多重度 (`cardinality`) も除外しない**。 同じ行に 2 件並べない決まりがあり、
 * 文字を書いた矢印ではこちらの知らせが先に出るため、多重度だけ別の知らせに回すと 1 行に 2 件並ぶ。
 */
export const 向きだけを使う図が伝えない矢印の欄: ReadonlySet<string> = new Set([
  "no",
  "from",
  "to",
  "pos",
  "fromPartNode",
  "toPartNode",
]);

/**
 * 矢印に書いた欄のうち、効かないものの呼び名を並べる (#2366)。
 *
 * **伝える欄を並べず、描く欄を除いた残り全部を返す**。 効かない欄を並べる形にすると、
 * 矢印に欄を足した日にその欄だけが一覧から漏れ、書いた人には「書いたのに何も起きない」
 * としか見えない。 除外側を書けば、足し忘れは「余計に知らせる」 側へ倒れる。
 *
 * 空の文字は書いていない扱いにする = 記法は矢印の行に必ず文字の欄を作るため、
 * 空でも「書いた」 とみなすと全ての矢印に知らせが出る。
 *
 * @param 矢印 記法から読んだ矢印 1 本
 * @param 伝えない欄 その図種が描く欄と、別の知らせが受け持つ欄
 * @returns 知らせに出す呼び名。 空なら伝えるものが無い
 */
export function 効かない矢印の欄を並べる(矢印: object, 伝えない欄: ReadonlySet<string>): string[] {
  const 残り = new Set(
    Object.entries(矢印 as Record<string, unknown>)
      .filter(([欄, 値]) => 値 !== undefined && !伝えない欄.has(欄))
      .map(([欄]) => 欄),
  );
  if (((矢印 as { label?: string }).label ?? "") === "") 残り.delete("label");
  const 効かない: string[] = [];
  for (const [欄, 呼び名] of 効かない矢印の欄の呼び名) {
    if (!残り.delete(欄)) continue;
    if (!効かない.includes(呼び名)) 効かない.push(呼び名);
  }
  // 呼び名を持たない欄は名前をそのまま出す = 読みにくい名前でも、黙って落とすよりは伝わる
  効かない.push(...[...残り].sort());
  return 効かない;
}
