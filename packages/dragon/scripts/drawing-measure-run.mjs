/**
 * 図を測る走査の進み方 (#2673)。
 *
 * 全部を測る走査は 11 群を順に開くため 40 分を超える。 その長さだと、途中の 1 枚が
 * 開けないことは例外ではなく起きる。 投げると、それまでに測った分が 1 件も残らない
 * (実測 = `interactive` 群の 1 枚で止まり、先に測った 10 群ぶんが消えた。 書き出しは
 * 走査の最後にあるため、途中経過の file も作られない)。
 *
 * そこで **失敗を投げずに値として返す**。 受け先は道具が既に持っている
 * 「測れなかった図」 の区分で、新しい区分は作らない。
 * 0 にも空にも潰さない (測れた 0% と、測っていないことは別の状態)。
 *
 * playwright を呼ぶ部分は引数で受け取る。 browser を持たないので検査から直に動かせる。
 */

/** error の 1 行目。 言い換えずにそのまま持つ = 次に同じ失敗を見た時に原因へ辿れる */
export function 理由の一行(e) {
  return String(e?.message ?? e)
    .split("\n")[0]
    .trim();
}

/**
 * 書いてある省略の印が持つ値 (#2677)。
 *
 * engine が幅に入らず切った名前も末尾が `…` になるため、描いた結果からは
 * 書いてある省略と切れた名前が同じ形に見える。 engine は書いてある方に
 * `data-cdl-ellipsis="written"` を付けるので、道具はその印で分ける。
 *
 * 印を持つ engine でしか分けられないが、印を持たない版では全部が「切れた名前」 に数えられる
 * = 見落とす側ではなく、過剰に報告する側へ倒れる。
 */
export const 書いてある印 = "written";

/**
 * 描いた文字 1 つが「engine が切った名前」 か (#2677)。
 *
 * 末尾が `…` かどうかだけで見ない。 それだと書いてある省略 (`0x…`) を数えてしまい、
 * 見本帳の 486 枚で「切れた名前 20 件」 と出ていたものが全部それだった。
 *
 * 途中に `…` を含む名前 (`pie / bar / …` のような書き方) は切れていない。
 */
export function 切れた名前か(文字) {
  if (!(文字?.文字 ?? "").endsWith("…")) return false;
  return 文字.省略の印 !== 書いてある印;
}

/**
 * 拾った文字から 3 つの数を出す (#2677)。
 *
 * 画面の中で数えず、拾った材料を外へ返してから数える。 画面の中の処理は browser でしか
 * 動かせないため、中で数えると数え方に検査を当てられない。
 */
export function 文字を数える(文字ら) {
  let 切れ = 0;
  let 字 = 0;
  for (const t of 文字ら) {
    if (切れた名前か(t)) 切れ += 1;
    // 読める字は、省略の印と空白を除いた数。 折り返しの改行を 1 字と数えると、
    // 同じ名前が枠の幅で増減する
    字 += (t.文字 ?? "").replace(/[\s…]/g, "").length;
  }
  return { 文字の件数: 文字ら.length, 切れた名前: 切れ, 読める字: 字 };
}

/** 読む回数の上限と、落ち着いたとみなす据え置きの回数 (#2675) */
export const 上限の既定 = 30;
export const 落ち着きの既定 = 5;

/**
 * 今の読みが、これまでの最大を上回るか。
 *
 * 広がりが並んだ時は文字の件数が多いほうを採る = より多く描かれている。
 * 数ごとに最大を採らない。 3 つの数が別々の瞬間から出ると、広がりは引き終わり、
 * 切れは引き始め、という組み合わせになり、同じ絵を表さなくなる。
 */
export function より広い(v, 最大) {
  if (!v) return false;
  if (最大 === null) return true;
  if (v.広がり > 最大.広がり) return true;
  return v.広がり === 最大.広がり && v.文字の件数 > 最大.文字の件数;
}

/**
 * 同じ図を、値が伸びなくなるまで読む (#2675)。
 *
 * 読む回数を決め打ちにすると、**描き終わる前の値が最後の値になる**。
 * 線を引く動きは繰り返すので待てば必ず全部描かれるが、それは窓が繰り返しの周期より
 * 長い時にだけ成り立つ。 実測では窓 1.8 秒で `tree-demo` が 11% / 文字 3 件、
 * 窓 10 秒で 28% / 文字 5 件 と 2.5 倍ちがった。
 *
 * 一律に窓を伸ばす形は採らない。 見本帳の図を 1 枚あたり 10 秒で測ると、全部で数時間かかる
 * (枚数は catalog が持つ)。 1.8 秒で落ち着く図も多く、その待ち時間まで増える。
 *
 * **落ち着きの判定は「採った 1 回が入れ替わったか」 で見る**。 広がりの値だけを見ると、
 * 広がりが同じまま文字の件数だけ増えている途中で止まる。
 *
 * 上限まで入れ替わり続けた図は `読み切れた: false` を持って返る。 値は捨てない
 * (捨てると相手選びから消えるが、消えたことが一覧に出ない)。
 */
export async function 落ち着くまで読む({
  読む,
  待つ,
  上限 = 上限の既定,
  落ち着き = 落ち着きの既定,
}) {
  let 最大 = null;
  let 据え置き = 0;
  let 回 = 0;
  let 落ち着いた = false;
  while (回 < 上限) {
    const v = await 読む();
    回 += 1;
    if (より広い(v, 最大)) {
      最大 = v;
      据え置き = 0;
    } else {
      据え置き += 1;
    }
    if (据え置き >= 落ち着き) {
      落ち着いた = true;
      break;
    }
    await 待つ?.();
  }
  if (最大 === null) return null;
  return { ...最大, 読んだ回数: 回, 読み切れた: 落ち着いた };
}

/**
 * 図 1 枚を測る。 投げない。
 *
 * 失敗は 3 通りに分かれ、どれも「測れなかった」 として返る。
 *
 * | どこで | `なぜ` に入る形 |
 * |---|---|
 * | 図を押す段 | `押せない ... {理由}` |
 * | 図を読む段 | `読めない ... {理由}` |
 * | 読めたが枠が無い | `枠を持つ SVG が無い` |
 */
export async function 一枚を測る(group, id, { 押す, 測る, 報せる }) {
  報せる?.(`${group}/${id}`);
  try {
    await 押す();
  } catch (e) {
    return { group, id, 測れた: false, なぜ: `押せない ... ${理由の一行(e)}` };
  }
  let v;
  try {
    v = await 測る();
  } catch (e) {
    return { group, id, 測れた: false, なぜ: `読めない ... ${理由の一行(e)}` };
  }
  if (!v) return { group, id, 測れた: false, なぜ: "枠を持つ SVG が無い" };
  return { group, id, 測れた: true, ...v };
}

/**
 * 群 1 つを測る。 投げない。
 *
 * 群を開けない形も同じ = 1 群で走査を終えると、残りの群が丸ごと失われる。
 * 群ごと落ちた時は 1 行だけ返す。 その群に何枚あったかは開けていないので判らず、
 * 枚数を仮に置くと測っていない図を数えたことになる。
 */
export async function 一群を測る(group, { 開く, 一覧, 一枚 }) {
  try {
    await 開く();
  } catch (e) {
    return [{ group, id: "(群ごと)", 測れた: false, なぜ: `開けない ... ${理由の一行(e)}` }];
  }
  let ids;
  try {
    ids = await 一覧();
  } catch (e) {
    return [{ group, id: "(群ごと)", 測れた: false, なぜ: `一覧を読めない ... ${理由の一行(e)}` }];
  }
  const out = [];
  for (const id of ids) out.push(await 一枚(group, id));
  return out;
}
