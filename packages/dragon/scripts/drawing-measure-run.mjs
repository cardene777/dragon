/**
 * 図を測る走査の進み方 (#2673)。
 *
 * 全部を測る走査は 11 群を順に開くため 40 分を超える。 その長さだと、途中の 1 枚が
 * 開けないことは例外ではなく起きる。 投げると、それまでに測った分が 1 件も残らない
 * (実測 = `interactive` 群の 1 枚で止まり、先に測った 10 群ぶんが消えた。 書き出しは
 * 走査の最後にあるため、途中経過の file も作られない)。
 *
 * そこで **失敗を投げずに値として返す**。 受け先は道具が既に持っている
 * 「測れなかった図」 の区分で、新しい区分は作らない。
 * 0 にも空にも潰さない (測れた 0% と、測っていないことは別の状態)。
 *
 * playwright を呼ぶ部分は引数で受け取る。 browser を持たないので検査から直に動かせる。
 */

/** error の 1 行目。 言い換えずにそのまま持つ = 次に同じ失敗を見た時に原因へ辿れる */
export function 理由の一行(e) {
  return String(e?.message ?? e)
    .split("\n")[0]
    .trim();
}

/**
 * 図 1 枚を測る。 投げない。
 *
 * 失敗は 3 通りに分かれ、どれも「測れなかった」 として返る。
 *
 * | どこで | `なぜ` に入る形 |
 * |---|---|
 * | 図を押す段 | `押せない ... {理由}` |
 * | 図を読む段 | `読めない ... {理由}` |
 * | 読めたが枠が無い | `枠を持つ SVG が無い` |
 */
export async function 一枚を測る(group, id, { 押す, 測る, 報せる }) {
  報せる?.(`${group}/${id}`);
  try {
    await 押す();
  } catch (e) {
    return { group, id, 測れた: false, なぜ: `押せない ... ${理由の一行(e)}` };
  }
  let v;
  try {
    v = await 測る();
  } catch (e) {
    return { group, id, 測れた: false, なぜ: `読めない ... ${理由の一行(e)}` };
  }
  if (!v) return { group, id, 測れた: false, なぜ: "枠を持つ SVG が無い" };
  return { group, id, 測れた: true, ...v };
}

/**
 * 群 1 つを測る。 投げない。
 *
 * 群を開けない形も同じ = 1 群で走査を終えると、残りの群が丸ごと失われる。
 * 群ごと落ちた時は 1 行だけ返す。 その群に何枚あったかは開けていないので判らず、
 * 枚数を仮に置くと測っていない図を数えたことになる。
 */
export async function 一群を測る(group, { 開く, 一覧, 一枚 }) {
  try {
    await 開く();
  } catch (e) {
    return [{ group, id: "(群ごと)", 測れた: false, なぜ: `開けない ... ${理由の一行(e)}` }];
  }
  let ids;
  try {
    ids = await 一覧();
  } catch (e) {
    return [{ group, id: "(群ごと)", 測れた: false, なぜ: `一覧を読めない ... ${理由の一行(e)}` }];
  }
  const out = [];
  for (const id of ids) out.push(await 一枚(group, id));
  return out;
}
