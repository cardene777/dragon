/**
 * 段ごとの markup を、いつの時点のものとして受け取るかを決める。
 *
 * 画面を開く側 (`design-export.mjs`) と分けてあるのは、こちらが playwright を持たない
 * 純関数で単体で確かめられるから。 開く側は読み取った markup を渡すだけにする。
 *
 * 段が変わった **その場で** 控えると、線を引く動きの途中を焼く。 線本体は進行に応じて
 * 切り詰められる一方、その下に敷く光は経路を丸ごと使うので、矢の先に光だけの棒が残る。
 * 意匠帳の `look.svg` はこの markup を焼き付けるため、引きかけの絵が永久に残る (#1543)。
 */

/** 1 つの塊から、その役割の `d` を取る。 属性の並び順は engine 任せなので両向きを見る */
function pathOf(chunk, role) {
  const 後 = new RegExp(`<path[^>]*data-cdl-role="${role}"[^>]*\\sd="([^"]+)"`).exec(chunk);
  if (後) return 後[1];
  const 前 = new RegExp(`<path[^>]*\\sd="([^"]+)"[^>]*data-cdl-role="${role}"`).exec(chunk);
  return 前 ? 前[1] : null;
}

/**
 * 引き終わっているか。
 *
 * 待つ長さを決め打ちにしない = 段の長さは engine が DOM に出しておらず、記法から辿っても
 * 段の id と対応が付かない。 「まだ引いている」 ことは markup 自身に出るので、そちらを見る。
 *
 * 判定は **光と線の経路が一致するか**。 光は `edge.d` を丸ごと使い、線は進行の分だけ
 * 切り詰めた path を持つので、引いている間だけ 2 つがずれる。
 *
 * 光を持たない図 (辺が無い / どの辺も光っていない) は判定材料が無い。 これを「引き終わった」
 * と読むと待ちが効かなくなるため、**判定できたか** を件数で返して呼出側に委ねる。
 */
export function 引き終わり(svg) {
  const 塊 = String(svg ?? "").split('<g data-cdl-edge="').slice(1);
  let 見た = 0;
  const 途中 = [];
  for (const c of 塊) {
    const 線 = pathOf(c, "edge-line");
    const 光 = pathOf(c, "edge-glow");
    if (線 === null || 光 === null) continue;
    見た += 1;
    if (線 !== 光) 途中.push(c.slice(0, c.indexOf('"')));
  }
  return { 見た, 途中, 引き終わった: 見た > 0 && 途中.length === 0 };
}

/**
 * 待った後の読み取りを、その段のものとして受け取ってよいか。
 *
 * 2 つを満たす時だけ受け取る。 待つ前と後で **段が変わっていない** ことと、
 * 判定できた辺があるなら **引き終わっている** こと。
 *
 * 待つ間に次の段へ進んでいたら、手にある markup は別の段のものなので捨てる = 捨てないと
 * 前の段の名前で次の段の絵を控える。 捨てた段は次の周で拾い直す (画面は段を繰り返す)。
 *
 * 判定できる辺が 1 本も無い図は、段さえ変わっていなければ受け取る。 待っても判る材料が
 * 増えないため、待ち続けると段を 1 つも控えられずに終わる。
 */
export function 受け取れるか(検知, 落ち着き) {
  if (!検知?.phase || !検知.svg) return { 受け取る: false, なぜ: "検知が空" };
  if (!落ち着き?.phase || !落ち着き.svg) return { 受け取る: false, なぜ: "読み直しが空" };
  if (検知.phase !== 落ち着き.phase) {
    return { 受け取る: false, なぜ: `待つ間に ${検知.phase} から ${落ち着き.phase} へ進んだ` };
  }
  const 状態 = 引き終わり(落ち着き.svg);
  if (状態.見た === 0) return { 受け取る: true, なぜ: "引き終わりを判じる辺が無い" };
  if (!状態.引き終わった) {
    return { 受け取る: false, なぜ: `まだ引いている辺が ${状態.途中.length} 本 (${状態.途中.join(" ")})` };
  }
  return { 受け取る: true, なぜ: `${状態.見た} 本とも引き終わっている` };
}
